-- 1) legal_docs 테이블 --------------------------------------
create table if not exists public.legal_docs (
  id          uuid primary key default gen_random_uuid(),
  slug        text unique not null,   -- privacy, terms, terms-applicant, 또는 신규
  title       text not null,          -- 제목(부제 span 등 HTML 허용)
  meta        text,                   -- 상단 메타 줄(운영/시행일 등)
  body        text not null,          -- 본문(HTML)
  sort_order  int  not null default 0,
  published   boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz
);

alter table public.legal_docs enable row level security;

-- 공개: 게시된 약관만 읽기
drop policy if exists "legal public read" on public.legal_docs;
create policy "legal public read" on public.legal_docs
  for select using (published = true);

-- 관리자: 전체 CRUD
drop policy if exists "legal admin all" on public.legal_docs;
create policy "legal admin all" on public.legal_docs
  for all to authenticated
  using      (auth.jwt() ->> 'email' in (select email from public.admins))
  with check (auth.jwt() ->> 'email' in (select email from public.admins));

