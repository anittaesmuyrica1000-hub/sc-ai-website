## 제3조. 약관의 명시와 개정

회사는 본 약관을 서비스 홈페이지에 게시하여 지원자가 언제든지 확인할 수 있도록 합니다.

회사는 관련 법령을 위배하지 않는 범위에서 약관을 개정할 수 있으며, 개정 시 적용일자 및 개정사유를 사전에 공지합니다.

지원자의 권리·의무에 중대한 영향을 미치는 변경은 합리적인 기간을 두고 사전 공지합니다.

## 제4조. 약관의 해석

회사가 필요하다고 판단한 경우 회사와 지원자는 별도의 서면 계약을 체결할 수 있습니다. 본 약관과 서면 계약의 내용이 충돌할 경우 서면 계약의 내용이 우선합니다.

본 약관에서 규정하지 않은 사항에 관해서는 「약관의 규제에 관한 법률」, 「전기통신기본법」, 「전기통신사업법」, 「정보통신망 이용촉진 및 정보보호 등에 관한 법률」, 「개인정보 보호법」 등의 관계법령에 따릅니다.

## 제5조. 이용계약의 성립

이용계약은 지원자가 약관에 동의하고, AI 면접 초대를 수락하여 절차를 진행함으로써 성립합니다.

지원자는 만 14세 이상만 이용할 수 있으며, 회사는 합리적 사유가 있는 경우 이용을 제한할 수 있습니다.

## 제6조. 개인 정보의 보호 및 관리

개인정보의 처리(수집·이용·제공·위탁·보관·파기)는 회사의 지원자 개인정보처리방침에 따릅니다.

## 제7조. 개인정보의 위탁

회사는 서비스 제공을 위해 필요한 경우 외부 업체에 개인정보 처리업무를 위탁할 수 있으며, 구체 내용은 개인정보처리방침에 공개합니다

회사는 위탁업체에 대하여 필요한 보호조치를 요구하고 감독합니다.

## 제8조. 지원자의 계정 및 비밀번호

지원자는 면접 응시를 위해 본인의 정확한 정보를 제공해야 합니다.

지원자는 본인의 이메일 및 접속 링크를 타인에게 공유해서는 안 되며, 관리 소홀로 발생하는 모든 책임은 지원자에게 있습니다.

## 제9조. 지원자에 대한 통지

회사는 지원자가 제공한 이메일 주소 또는 서비스 내 공지사항을 통해 지원자에게 필요한 정보를 통지할 수 있습니다.

## 제10조. 서비스의 제공 및 중지

회사는 AI 면접, 질문 생성, 분석 리포트 생성 및 채용사 제공 기능을 제공합니다.

회사는 점검, 장애, 운영상 필요 시 서비스의 전부 또는 일부를 일시 중지할 수 있습니다.

## 제11조. AI 면접 서비스

AI는 채용사가 제공한 채용 공고를 기반으로 핵심 역량과 질문을 자동 생성합니다. 채용사는 생성된 질문과 역량을 검토, 수정하거나 직접 추가 질문을 구성할 수 있으며, 지원자에게는 채용사가 최종적으로 확정한 질문이 제시됩니다.

AI 면접 진행 중 지원자의 영상·음성 및 응답 내용이 기록·수집되며, 면접 종료 후 분석 리포트와 함께 채용사에게 제공됩니다. 데이터 처리의 상세 범위는 개인정보 처리방침에 따릅니다.

AI는 면접 진행 과정에서 지원자의 답변 내용 및 맥락을 실시간으로 분석하여, 이에 대응하는 추가 질문(꼬리 질문)을 생성하고 제시할 수 있습니다.

면접 종료 후 생성되는 분석 리포트는 AI의 기계적 분석 결과와 채용사가 설정한 평가 기준을 결합하여 도출되는 의사결정 보조 자료입니다. 채용의 최종 합격 여부는 채용 담당자가 해당 분석 리포트와 면접 데이터를 종합적으로 검토하여 결정하며, AI가 독단적으로 합불을 결정하지 않습니다.

지원자는 채용사가 설정한 응시 기한 내에 면접을 완료해야 합니다. 채용사의 구독 서비스 기간 종료, 이용 한도 소멸 또는 회사의 시스템 운영 정책에 따른 프로젝트 마감 이후에는 응시가 불가능할 수 있으며, 지원자의 미응시로 인한 불이익에 대해 회사는 귀책 사유가 없는 한 책임을 지지 않습니다.

