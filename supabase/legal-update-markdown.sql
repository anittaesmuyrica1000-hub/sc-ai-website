## 제3조. 약관의 명시와 개정

회사는 본 약관을 서비스 홈페이지에 게시하여 회원이 언제든지 확인할 수 있도록 합니다.

회사는 관련 법령을 위배하지 않는 범위에서 약관을 개정할 수 있으며, 개정 시 적용일자 및 개정사유를 사전에 공지합니다.

회원의 권리·의무에 중대한 영향을 미치는 변경은 합리적인 기간을 두고 사전 공지합니다.

## 제4조. 약관의 해석

회사가 필요하다고 판단한 경우 회사와 회원은 별도의 서면 계약을 체결할 수 있습니다. 본 약관과 서면 계약의 내용이 충돌할 경우 서면 계약의 내용이 우선합니다.

본 약관에서 규정하지 않은 사항에 관해서는 「약관의 규제에 관한 법률」, 「전기통신기본법」, 「전기통신사업법」, 「정보통신망 이용촉진 및 정보보호 등에 관한 법률」, 「개인정보 보호법」 등의 관계법령에 따릅니다.

## 제5조. 이용계약의 성립

이용계약은 회원이 약관에 동의하고 회사가 정한 절차에 따라 계정을 생성하거나 주문/구매를 완료함으로써 성립합니다.

회사는 업무상·기술상 사유가 있는 경우 가입/이용을 승낙하지 않거나 유보할 수 있습니다.

회원은 실사용 담당자의 최신 정보를 유지해야 하며, 미갱신으로 인한 불이익은 회원에게 귀속됩니다.

## 제6조. 증빙 자료의 제출

회사는 서비스 제공 및 정산/보안/권한 관리를 위해 회원에게 사업자등록증, 재직증명서, 권한 위임 확인 등 증빙자료 제출을 요청할 수 있습니다.

## 제7조. 개인 정보의 보호 및 관리

서비스 이용 과정에서 처리되는 개인정보는 회사의 개인정보처리방침 및 관련 법령에 따라 처리됩니다.

회원은 지원자 개인정보를 적법하게 수집·이용·제공해야 하며, 지원자에게 필요한 고지 및 동의(제3자 제공 동의 포함)를 적법하게 확보하고, 내부 권한통제를 갖추어야 합니다..

회사는 개인정보처리자로서 서비스 제공을 위하여 지원자의 개인정보(면접데이터 포함)를 처리할 수 있으며, 지원자의 동의 또는 법령상 근거가 있는 경우에 한하여 회원에게 해당 개인정보를 제3자 제공할 수 있습니다.

제3항의 제3자 제공은 회원의 채용전형 진행(평가·검토 및 결과 확인) 목적 범위 내에서 이루어지며, 구체적인 제공 항목, 제공 시점 및 제공 방법은 서비스 설정 및 개인정보처리방침에서 정하는 바에 따릅니다.

회원은 회사로부터 제공받은 지원자 개인정보 및 면접데이터를 채용 목적 외로 이용하거나 제3자에게 제공하여서는 아니 되며, 관계 법령 및 본 약관을 준수하여 안전하게 관리·보관·파기하여야 합니다.

## 제8조. 개인정보의 위탁

회사는 서비스 제공을 위해 필요한 경우 외부 업체에 개인정보 처리업무를 위탁할 수 있으며, 구체 내용은 개인정보처리방침에 공개합니다.

회사는 위탁업체에 대하여 필요한 보호조치를 요구하고 감독합니다.

## 제9조. 회원의 계정 및 비밀번호

회원은 계정정보의 정확성 및 최신성을 유지해야 합니다.

회원은 계정/접근권한을 제3자에게 공유·양도·대여할 수 없으며, 관리자 권한은 최소 인원에게만 부여해야 합니다.

회원의 관리 소홀로 발생한 손해는 회원에게 귀속됩니다.

## 제10조. 회원에 대한 통지

회사는 회원이 제공한 이메일 주소 또는 서비스 내 공지사항을 통해 회원에게 필요한 정보를 통지할 수 있습니다.

## 제11조. 서비스의 제공 및 중지

회사는 AI 면접, 질문 생성, 분석 리포트 생성 및 채용사 제공 기능을 제공합니다.

회사는 점검, 장애, 운영상 필요 시 서비스의 전부 또는 일부를 일시 중지할 수 있습니다.

## 제12조. AI 면접 서비스

AI는 채용공고 및 회원이 설정한 평가요소를 기반으로 질문/역량을 생성할 수 있습니다. 회원은 생성된 질문/역량을 검토·수정·추가하여 최종 확정할 수 있습니다.

AI 면접 진행 중 지원자의 영상·음성 등이 기록될 수 있으며, 면접 종료 후 분석 리포트 및 면접데이터가 회원에게 제공될 수 있습니다. 제공 범위는 서비스 설정 및 개인정보처리방침에 따릅니다.

AI는 지원자 답변을 기반으로 후속 질문을 생성할 수 있습니다.

분석 리포트는 참고자료이며, 회원은 채용 결정을 위해 독자적 기준과 절차로 종합 판단해야 합니다.

회원은 지원자에게 AI 면접의 진행 방식, 데이터 처리 및 제공 사실을 적법하게 고지하고 필요한 동의를 확보해야 합니다.

## 제13조. 서비스의 내용 변경

회사는 기술적 사양의 변경이나 서비스 품질 향상을 위해 서비스 내용을 변경할 수 있으며, 이 경우 변경 사항을 사전에 공지합니다.

## 제14조. 정보의 제공 및 광고의 게재

회사는 서비스 운영/고객지원/업데이트 안내를 위해 필요한 정보를 공지 또는 메시지로 제공할 수 있습니다.

회사는 서비스 화면에 제3자의 광고를 게재할 수 있으며, 회원과 광고주 간 거래는 당사자 책임으로 합니다.

## 제15조. 게시물과 권리의 귀속 등

면접데이터 중 회사가 생성한 질문, 분석 리포트 템플릿 등 지식재산권은 회사에 귀속됩니다.

회원이 서비스에 등록한 채용공고/평가요소/질문 등(이하 “회원 콘텐츠”)의 권리는 회원에게 귀속됩니다.

회원은 서비스 제공 및 운영을 위해 필요한 범위에서 회사가 회원 콘텐츠를 저장·복제·표시·전송할 수 있도록 비독점적 라이선스를 부여합니다.

회원이 플랫폼에서 회원 콘텐츠를 삭제하면, 회사에 대한 라이선스는 향후 사용에 대해 자동 종료됩니다. 다만 (i) 감사, 백업, 법규 준수, 사업 연속성 목적의 보관/캐시, (ii) 이미 제3자에게 적법하게 제공·배포된 자료에 대하여는 완전한 회수가 불가능할 수 있으며, 삭제 이전의 사용에 소급 적용되지 않습니다.

회원은 회원 콘텐츠가 제3자의 권리를 침해하지 않음을 보증하며, 침해 분쟁 발생 시 회원의 책임과 비용으로 해결하고 회사를 면책해야 합니다.

회원은 면접데이터 및 지원자 정보를 채용 목적 외로 이용하거나 제3자에게 무단 제공할 수 없습니다.

## 제16조. 이용제한

회사는 시스템 해킹, 비정상적인 접근 등 서비스의 기술적 운영을 방해하는 회원에 대해 이용을 제한할 수 있습니다. 단, 답변 내용의 허위 여부에 따른 제재는 채용 회사의 결정에 따릅니다.

회사는 이용 제한 전 합리적인 범위에서 사전 통지할 수 있으나, 긴급한 보안 사유가 있으면 즉시 제한 후 사후 통지할 수 있습니다.

## 제17조. 회원의 계약해제·해지 등

회원은 회사가 정한 절차(관리자 요청/서면/고객센터 등)로 이용계약의 해지(탈퇴)를 신청할 수 있습니다.

해지 시점, 데이터 접근 제한, 데이터 반환/삭제, 잔여 이용대금 정산 등은 본 약관 및 개별 계약/정책에 따릅니다.

해지 후에도 미결제 대금, 지식재산권, 비밀유지, 책임제한 등 성질상 존속이 필요한 조항은 유효합니다.

## 제18조. 유료서비스 이용요금

유료서비스의 종류, 과금 기준, 금액, 결제 주기 등은 서비스 화면, 견적서/주문서 또는 개별 계약에서 정합니다.

회사는 운영상 필요 시 요금제를 변경할 수 있으며, 중요한 변경은 사전 고지합니다.

## 제19조. 구독 플랜 및 이용 한도(크레딧)

회원은 선택한 구독 플랜에 따라 정해진 기간(이하 “구독 기간”) 동안 서비스를 이용할 수 있는 이용 한도(이하 “크레딧”)를 부여받습니다. 유상으로 구매한 크레딧의 유효기간은 해당 구독 기간(기본 30일)으로 제한됩니다

회사는 실시간 AI 분석 및 지원자 응시 환경의 안정성을 보장하기 위해 전체 시스템 자원을 최적화하고 운영 효율성을 관리합니다. 회사는 이러한 안정적인 인프라 유지 및 서비스 품질 보전을 위한 운영 정책에 따라, 구독 기간 내에 사용하지 않은 잔여 크레딧을 기간 만료 시 자동 소멸시키며 다음 주기로 이월하거나 환불하지 않습니다. 단, 별도의 서면 계약을 통해 기간을 정한 경우에는 해당 계약이 우선합니다.

회원은 서비스 이용 방식에 따라 다음과 같은 시점에 크레딧을 차감하는 것에 동의합니다.

직접 초대 (이메일 발송): 회원이 특정 지원자에게 면접 초대 메일을 발송하는 시점에 해당 인원수만큼 크레딧이 즉시 차감됩니다.

공유 링크 응시: 회원이 생성한 공유 링크를 통해 지원자가 접속하여, 이용약관 동의하는 시점에 크레딧이 차감됩니다.

API 연동 생성: 회원이 API를 통해 지원자를 생성하는 시점에 해당 인원수만큼 크레딧이 즉시 차감됩니다.

제3항에 따라 크레딧이 선차감되었으나, 지원자가 실제 면접을 시작(카메라/마이크 테스트 진입 등)하지 않은 상태에서 해당 프로젝트가 종료(마감 기한 경과 또는 회원의 강제 종료)되는 경우, 회사는 해당 건에 한해 차감되었던 크레딧을 해당 구독 기간 내의 잔여 한도로 복구합니다. 단, 구독 기간 자체가 만료된 경우에는 복구되지 않습니다.

무료 체험용 크레딧(10건) 및 기타 프로모션으로 지급된 무상 크레딧은 회사가 별도로 정한 유효기간 및 조건이 우선 적용되며, 유상 크레딧보다 우선하여 차감될 수 있습니다.

## 제20조. 유료서비스 결제

결제수단은 카드/계좌이체/세금계산서 등으로 하며, 세부 절차는 회사의 안내에 따릅니다.

회원이 결제 정보를 정확히 제공하지 않거나 결제 불이행이 발생할 경우, 회사는 서비스 제공을 제한할 수 있습니다.

## 제21조. 청약철회 및 환불

회원은 구독 서비스 결제 후 이용 내역이 없는 경우에 한하여 「전자상거래 등에서의 소비자보호에 관한 법률」에 따라 결제일로부터 7일 이내에 청약철회(환불)를 요청할 수 있습니다.

본 서비스는 결제와 동시에 이용 한도(크레딧)가 부여되며, 다음 각 호의 어느 하나에 해당하는 경우 이용자가 서비스를 이용(디지털 콘텐츠의 실행)한 것으로 간주하여 청약철회가 제한됩니다.

직접 초대, 공유 링크 생성, API 연동 등을 통해 최소 1건 이상의 이용 한도(크레딧)가 차감된 경우

서비스 내 분석 리포트 확인, 질문 생성 기능을 사용한 경우

기타 서비스 이용을 위해 회사가 제공하는 리소스를 실질적으로 사용한 경우

제2항에 따라 청약철회가 제한되는 경우, 해당 구독 회차에 대해 지불한 구독료는 반환되지 않습니다. 단, 다음 결제 주기부터 서비스 이용을 중단하고자 하는 경우 '구독 해지(다음 결제 예약 취소)'를 신청할 수 있으며, 이 경우 이미 결제된 남은 구독 기간까지는 서비스를 정상적으로 이용할 수 있습니다.

회원의 환불 요청 시 회사가 부담한 결제대행업체(PG) 수수료, 송금 수수료 등 부대 비용이 발생하는 경우 환불 금액에서 해당 비용을 공제할 수 있습니다.

회사의 명백한 귀책(서비스의 영구적 중단 등)으로 인해 서비스를 이용하지 못한 경우에는 관련 법령에 따라 잔여 기간을 산정하여 환불 조치합니다.

## 제22조. 이용요금 과오납의 조정

회사의 귀책으로 과오납이 발생한 경우 과오납 금액을 환급합니다.

과오납 정산 절차는 회사의 안내에 따릅니다.

## 제23조. 회사의 의무

회사는 관련 법령 및 약관을 준수하고 안정적인 서비스 제공을 위해 노력합니다.

회사는 개인정보 보호를 위한 관리적·기술적 조치를 이행합니다.

## 제24조. 회원의 의무

회원은 지원자에게 필요한 고지/동의 및 내부 접근통제를 이행하고, 면접데이터의 열람/다운로드 권한을 최소화해야 합니다.

회원이 법령 또는 본 약관 위반으로 회사에 손해를 발생시킨 경우, 회원은 이를 배상해야 합니다.

## 제25조. 손해배상

회사의 고의 또는 중과실로 인해 회원에게 발생한 직접적인 손해에 대해서는 관련 법령에 따라 배상합니다.

회원의 귀책으로 회사 또는 제3자(지원자 포함)에게 손해가 발생한 경우, 회원은 회사에 발생한 손해를 배상하고 회사를 면책해야 합니다.

## 제26조. 책임 제한

회사는 천재지변, 정전, 통신망 장애 등 불가항력으로 인한 서비스 장애에 대해 책임을 부담하지 않습니다.

회사는 회원의 채용 결과(합격/불합격), 인사결정 및 그 결과를 보장하지 않습니다.

분석 리포트는 참고자료이며, 회원의 최종 판단 및 사용 방식에 따라 발생한 결과에 대해 회사는 법령상 허용되는 범위에서 책임을 제한합니다.

회원이 지원자 정보를 채용 목적 외로 이용하거나 유출한 경우 그 책임은 회원에게 귀속됩니다.

면접 데이터 보관 기간은 응시 완료일로부터 1년이며, 기간 경과 후 데이터 삭제로 인한 손실은 회사가 책임지지 않습니다.

