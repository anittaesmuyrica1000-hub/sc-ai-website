개인정보 파기의 절차 및 방법은 다음과 같습니다.파기절차 회사는 파기 사유가 발생한 개인정보를 선정하고, 회사의 개인정보 보호책임자의 승인을 받아 개인정보를 파기합니다.파기방법전자적 파일 형태: 회사는 클라우드 인프라에 기록·저장된 개인정보에 대하여 기록을 재생할 수 없도록 로우레벨 포맷(Low Level Format) 또는 이에 준하는 기술적 파기 방법을 이용하여 파기합니다.종이 문서: 종이 문서에 기록·저장된 개인정보는 분쇄기로 분쇄하거나 소각하여 파기합니다.

