1) 본 약관에서 사용하는 용어의 정의는 다음과 같습니다.

“AI 면접”이란 기업회원(이하 “채용사”)가 등록한 채용공고를 기반으로 회사가 생성한 질문에 따라 지원자가 영상·음성 방식으로 응시하고, 회사가 응답을 분석하여 분석 리포트를 생성하는 절차를 말합니다.

“채용사”란 지원자를 서비스로 초대한 기업 고객을 말합니다.

“면접데이터”란 AI 면접 과정에서 생성·수집되는 영상, 음성, 텍스트(전사/요약 포함), 질문/평가, 로그 등 일체를 말합니다.

“계정정보”란 지원자의 입력하는 이름, 이메일 및 인증/이력 관리에 필요한 정보를 말합니다.

