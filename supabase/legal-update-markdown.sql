## 제5조. 정보주체와 법정대리인의 권리·의무 및 그 행사 방법

정보주체는 회사에 대해 언제든지 개인정보 열람, 정정, 삭제, 처리정지 요구 등의 권리를 행사할 수 있습니다.

제1항에 따른 권리 행사는 회사에 대해 「개인정보 보호법」 시행령 제41조 제1항에 따라 서면, 전자우편 등을 통하여 하실 수 있으며, 회사는 이에 대해 지체 없이 조치하겠습니다.

정보주체가 개인정보의 오류 등에 대한 정정 또는 삭제를 요구한 경우에는 회사는 정정 또는 삭제를 완료할 때까지 당해 개인정보를 이용하거나 제공하지 않습니다.

제1항에 따른 권리 행사는 정보주체의 법정대리인이나 위임을 받은 자 등 대리인을 통하여 하실 수 있습니다. 이 경우 「개인정보 보호법」 시행규칙 별지 제11호 서식에 따른 위임장을 제출하셔야 합니다.

개인정보 열람 및 처리정지 요구는 「개인정보 보호법」 제35조 제4항, 제37조 제2항에 의하여 정보주체의 권리가 제한될 수 있습니다.

개인정보의 정정 및 삭제 요구는 다른 법령에서 그 개인정보가 수집 대상으로 명시되어 있는 경우에는 그 삭제를 요구할 수 없습니다.

회사는 정보주체 권리에 따른 열람의 요구, 정정·삭제의 요구, 처리정지의 요구 시 열람 등 요구를 한 자가 본인이거나 정당한 대리인인지를 확인합니다.

인공지능(AI) 기술을 활용한 자동화된 분석 등에 관한 사항회사는 AI를 활용하여 지원자의 답변을 분석하고 분석 리포트를 생성하는 시스템을 운영하고 있습니다. 정보주체는 본인의 권리 또는 의무에 중대한 영향을 미치는 자동화된 결정에 대하여 설명 및 검토를 요구할 수 있습니다.회사의 서비스는 AI 분석 리포트를 채용 의사결정의 보조 자료로 제공할 뿐이며, 최종적인 채용 전형의 합격 여부는 채용 담당자(사람)의 개입을 통해 결정됩니다. 따라서 「개인정보 보호법」 제37조의2에 따라 인적 개입이 없는 '완전 자동화된 결정'에 해당하지 않을 수 있으며, 이 경우 자동화된 결정에 대한 거부권 행사가 제한될 수 있습니다.

