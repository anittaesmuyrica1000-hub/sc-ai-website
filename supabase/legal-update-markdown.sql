## 제2조. 용어의 정의

1) 본 약관에서 사용하는 용어의 정의는 다음과 같습니다.

“서비스”란 회사가 제공하는 AI 면접, 질문 생성, 응답 수집, 분석 리포트 제공, 채용 프로세스 운영에 필요한 부가 기능 일체를 말합니다.

“회원”이란 본 약관에 동의하고 회사와 이용계약을 체결하여 서비스를 이용하는 기업 고객을 말합니다.

“프로젝트”란 회원이 특정 채용 공고를 위해 생성된 AI 면접 단위입니다.

“관리자”란 프로젝트의 생성/권한부여/결제 등 운영 권한을 가진 회원의 담당자를 말합니다.

“지원자”란 회원의 채용 전형에 참여하는 개인을 말합니다.

“AI 면접”이란 채용공고 및 회원이 설정한 평가요소를 기반으로 회사의 시스템이 질문을 생성·제시하고, 지원자의 영상·음성·텍스트 응답을 수집한 뒤 분석 리포트 등을 생성·제공하는 절차를 말합니다.

“면접데이터”란 AI 면접 과정에서 생성·수집·기록되는 영상, 음성, 텍스트(전사/요약 포함), 질문/평가, 로그 등 일체를 말합니다.

“유료서비스”란 회사가 정한 이용대가를 지불하고 이용하는 서비스를 말하며, 정해진 기간(이하 “구독 기간”) 동안 서비스 이용 권한을 부여받는 “구독 플랜” 형태를 포함합니다.

“이용 한도(이하 “크레딧”)”란 회원이 선택한 구독 플랜에 따라 해당 구독 기간 내에 지원자에게 서비스를 제공할 수 있는 최대 횟수 또는 단위를 말합니다.

“소멸”이란 구독 기간이 만료됨에 따라 해당 기간 내에 사용하지 않은 잔여 “크레딧”이 자동으로 사라지며, 다음 구독 기간으로 이월되지 않는 것을 말합니다.

