## 제3조. 약관의 명시와 개정

① 회사는 본 약관과 회사의 상호, 대표자 성명, 영업소 소재지, 사업자등록번호 및 연락처를 지원자가 쉽게 확인할 수 있도록 서비스 화면 또는 연결화면에 게시합니다.

② 회사는 관계 법령을 위반하지 않는 범위에서 본 약관을 개정할 수 있습니다.

③ 회사가 본 약관을 개정하는 경우 적용일자, 개정사유 및 주요 변경 내용을 명시하여 현행 약관과 함께 적용일 7일 전부터 서비스 화면 또는 회사 웹사이트에 게시합니다. 다만 지원자의 권리·의무에 중대한 영향을 미치거나 지원자에게 불리한 변경은 적용일 30일 전부터 게시하고, 회사가 연락처를 보유한 진행 중인 면접의 지원자에게 이메일 또는 서비스 화면 등으로 개별 통지합니다.

④ 개정약관은 적용일 이후 새로 본 약관에 동의하고 AI 면접 절차를 진행하는 지원자에게 적용됩니다. 적용일 전에 이미 본 약관에 동의한 면접 건에는 동의 당시의 약관을 적용합니다.

⑤ 회사가 진행 중인 면접 건에 개정약관을 적용할 필요가 있는 경우에는 변경 내용을 개별 통지하고 지원자의 명시적인 동의를 다시 받습니다. 다만 법령의 강행규정을 그대로 반영하거나 지원자에게 유리하고 기존 권리를 제한하지 않는 변경은 관계 법령이 허용하는 범위에서 별도의 재동의 없이 적용할 수 있습니다.

⑥ 개인정보 처리 목적·항목의 확대, 민감정보 처리, 제3자 제공 또는 국외이전 등 관계 법령상 별도의 동의가 필요한 변경은 본 조의 약관 개정 절차와 분리하여 필요한 동의를 별도로 받습니다.

⑦ 회사는 이전 약관과 개정 이력을 지원자가 확인할 수 있도록 보관·공개합니다.

## 제4조. 약관의 해석

① 개인정보 처리에 관한 구체적인 사항은 회사 또는 해당 채용사의 개인정보 처리방침과 면접 시작 전 지원자에게 제공되는 고지·동의 내용에 따릅니다.

② 본 약관과 제1항의 고지·동의 내용이 충돌하는 경우 개인정보 처리에 관해서는 관계 법령과 해당 개인정보 처리관계의 성격에 부합하는 구체적인 고지·동의 내용을 우선 적용합니다.

③ 본 약관에서 정하지 않은 사항은 「약관의 규제에 관한 법률」, 「정보통신망 이용촉진 및 정보보호 등에 관한 법률」, 「개인정보 보호법」, 「인공지능 발전과 신뢰 기반 조성 등에 관한 기본법」 등 관계 법령과 일반적인 상관례에 따릅니다.

④ 본 약관의 일부 조항이 관계 법령에 따라 무효가 되더라도 나머지 조항의 효력에는 영향을 미치지 않습니다.

## 제5조. 이용계약의 성립 및 이용자격

① 이용계약은 지원자가 본 약관의 내용을 확인하고 이에 동의한 후 AI 면접 초대 또는 공유 링크를 통하여 면접 절차를 진행함으로써 성립합니다.

② 지원자는 만 14세 이상인 경우에만 서비스를 이용할 수 있습니다.

③ 회사는 다음 각 호의 어느 하나에 해당하는 경우 이용 신청을 거절하거나 이용을 제한할 수 있습니다.

1. 지원자가 만 14세 미만인 경우
2. 타인의 명의를 사용하거나 대리 응시를 시도하는 경우
3. 지원자가 제공한 정보에 중대한 허위·누락·오류가 있는 경우
4. 서비스의 기술적·보안상 장애가 있거나 위법한 이용이 합리적으로 의심되는 경우
5. 그 밖에 이용을 허용하기 어려운 합리적인 사유가 있는 경우

④ 회사가 이용을 거절하거나 제한하는 경우 원칙적으로 지원자에게 그 사유를 알립니다. 다만 구체적인 사유의 공개로 보안 위험이나 제3자의 권리 침해가 발생할 우려가 있는 경우에는 안내 범위를 제한할 수 있습니다.

⑤ 만 14세 미만인 사람이 서비스에 접속한 사실을 회사가 확인한 경우 회사는 서비스 이용을 중단합니다. 회사가 개인정보처리자인 경우에는 관계 법령상 보존 의무가 있는 정보를 제외하고 해당 과정에서 수집한 개인정보를 지체 없이 삭제하며, 회사가 수탁자인 경우에는 해당 채용사에 알리고 관계 법령, 개인정보 처리위탁계약 및 채용사의 적법한 지시에 따라 처리합니다.

## 제6조. 개인정보 고지 및 동의 절차

① 회사가 개인정보처리자인 일반적인 서비스 이용관계에서는 회사가 AI 면접 시작 전에 다음 각 호의 사항을 서로 구분하여 안내하고, 관계 법령상 동의가 필요한 사항에 대하여 각각 별도의 동의를 받습니다.

1. 서비스 제공을 위한 개인정보의 수집·이용
2. 해당 채용사에 대한 개인정보 및 AI 면접 결과의 제3자 제공
3. 서비스 제공에 필요한 개인정보의 국외이전
4. 관계 법령상 별도 동의가 필요한 민감정보의 수집·이용

② 각 고지·동의 화면에는 개인정보 처리 주체, 처리 목적, 처리 항목, 보유·이용기간, 제공받는 자 또는 국외이전받는 자, 동의 거부 권리 및 거부에 따른 구체적인 영향을 표시합니다.

③ 지원자는 각 동의를 거부할 수 있습니다. 다만 AI 면접 제공에 필수적인 개인정보 처리에 동의하지 않으면 해당 기능의 이용 또는 채용사의 후속 채용 절차가 제한될 수 있으며, 구체적인 영향은 동의 화면에서 안내합니다.

④ 회사는 지원자가 선택적으로 동의할 수 있는 사항을 거부했다는 이유만으로 필수 서비스의 제공을 제한하지 않습니다.

⑤ 채용사가 개인정보처리자이고 회사가 수탁자인 프로젝트에서는 채용사가 관계 법령상 필요한 처리 근거와 고지·동의 절차를 마련하고, 회사는 채용사의 적법한 지시에 따라 개인정보를 처리합니다. 적용되는 개인정보 처리 주체와 권리 행사 창구는 면접 시작 전에 안내합니다.

⑥ 회사는 지원자의 약관 동의 및 개인정보 관련 동의 여부·일시·적용 문안·버전과 관계 법령상 필요한 확인 기록을 관리합니다.

## 제7조. 개인정보의 보호 및 권리 행사

① 개인정보의 수집·이용·제공·위탁·보관·파기는 관계 법령, 적용되는 개인정보 처리방침 및 면접 시작 전 지원자에게 제공되는 고지·동의 내용에 따릅니다.

② 일반적인 서비스 이용관계에서는 회사가 개인정보처리자로서 지원자의 개인정보를 처리하며, 지원자의 별도 동의 또는 법령상 근거에 따라 해당 채용사에 지원자의 개인정보와 AI 면접 결과를 제공합니다.

③ 채용사가 회사와 별도의 개인정보 처리위탁계약을 체결한 프로젝트에서는 채용사가 개인정보처리자이자 위탁자가 되고 회사는 채용사의 적법한 지시에 따라 개인정보를 처리하는 수탁자가 됩니다. 이 경우 해당 개인정보 처리위탁계약, 채용사의 개인정보 처리방침 및 지원자에게 제공된 고지·동의 내용이 함께 적용됩니다.

④ 회사는 지원자의 개인정보와 AI 면접 결과를 해당 지원자가 지원하거나 응시하는 채용사 외의 다른 채용사에 제공하거나 열람하게 하지 않습니다.

⑤ 지원자는 관계 법령에 따라 개인정보의 열람, 정정·삭제, 처리정지 및 동의 철회 등을 요구할 수 있습니다. 제2항의 경우 회사에, 제3항의 경우 원칙적으로 해당 채용사에 권리를 행사합니다.

⑥ 제3항의 프로젝트에 관한 권리 행사 요청이 회사에 접수된 경우 회사는 이를 해당 채용사에 전달하고 필요한 범위에서 처리에 협조합니다.

⑦ 구체적인 권리 행사 방법과 연락처는 적용되는 개인정보 처리방침 및 면접 화면에서 안내합니다.

## 제8조. 개인정보 처리의 위탁 및 국외이전

① 회사는 서비스 제공을 위해 필요한 경우 외부 업체에 개인정보 처리업무를 위탁할 수 있으며, 수탁업체와 위탁업무의 구체적인 내용은 개인정보 처리방침에 공개합니다.

② 회사는 수탁업체와 필요한 계약을 체결하고 개인정보가 안전하게 처리되도록 관리·감독합니다.

③ 서비스 제공 과정에서 개인정보의 국외이전이 발생하는 경우 이전되는 항목·국가·시기·방법·이전받는 자·이용 목적 및 보유기간 등은 개인정보 처리방침에서 공개하며, 회사와 채용사는 각자의 개인정보 처리 지위에 따라 관계 법령상 필요한 처리 근거와 고지·동의 절차를 마련합니다.

④ 지원자의 별도 동의 전에 국외에 위치한 이메일 서비스를 통하여 최초 초대 메일이 발송되는 경우 해당 정보 제공과 국외이전에 필요한 법적 근거는 채용사가 미리 확보합니다.

⑤ 일반적인 서비스 이용관계에서 면접 준비·진행을 위하여 회사가 수행하는 국외이전은 관계 법령상 다른 근거가 있는 경우를 제외하고 지원자의 별도 동의를 받은 후 이루어집니다.

⑥ 지원자는 국외이전에 대한 동의를 거부할 수 있습니다. 다만 해당 국외이전 없이는 제공하기 어려운 이메일 안내, 합성 음성 또는 실시간 영상·음성 전송 등 구체적인 기능이 제한될 수 있으며, 회사는 제한되는 기능을 동의 화면에서 안내합니다.

## 제9조. 면접데이터의 보관 및 삭제

① 채용사가 개인정보처리자이고 회사가 수탁자인 프로젝트의 개인정보와 면접데이터의 보유·반환·파기 기간은 해당 채용사의 개인정보 처리방침, 지원자에게 제공된 고지·동의, 개인정보 처리위탁계약 및 채용사의 적법한 지시에 따릅니다.

② 그 밖의 일반적인 서비스 이용관계에서 회사는 지원자의 개인정보와 면접데이터를 AI 면접 응시 완료일부터 1년간 보관하며, 면접에 응시하지 않은 경우 초대일부터 1년간 보관합니다. 지원자에게 이보다 짧은 기간이 고지된 경우에는 그 기간을 우선 적용합니다.

③ 제1항 또는 제2항의 보유기간이 지나기 전이라도 해당 채용공고·프로젝트 또는 면접 정보가 삭제되거나 회사가 적법한 삭제 요청을 받은 경우, 회사는 관계 법령상 보존 의무가 있는 정보를 제외하고 해당 정보를 지체 없이 파기합니다. 다만 제1항의 프로젝트에서는 개인정보 처리위탁계약과 채용사의 적법한 지시에 따라 반환하거나 파기합니다.

④ 채용사에 이미 제공된 정보의 보유·이용기간은 해당 채용사의 개인정보 처리방침과 지원자에게 제공된 고지·동의 내용에 따르며, 이에 관한 권리는 제7조에 따라 행사할 수 있습니다.

⑤ 회사가 본 조, 개인정보 처리방침 및 관계 법령에 따라 적법하게 정보를 삭제한 경우 지원자는 삭제된 정보의 복구를 요청할 수 없습니다. 다만 회사의 귀책사유로 정해진 보유기간 전에 정보가 삭제된 경우에는 그러하지 않습니다.

## 제10조. 응시 정보 및 접속수단의 관리

① 지원자는 면접 응시를 위하여 본인의 정확한 정보를 제공하여야 합니다.

② 지원자는 본인 확인 후 개인에게 발급된 고유 면접 링크, 인증정보 또는 진행 중인 면접 세션 정보를 타인에게 공유해서는 안 되며, 타인이 본인 명의로 응시하게 해서도 안 됩니다. 다만 채용사가 공개한 지원용 공유 링크 자체에는 본 항을 적용하지 않습니다.

③ 지원자는 개인 면접 링크 또는 인증정보의 도용이나 무단 사용을 인지한 경우 지체 없이 회사 또는 채용사에 알려야 합니다.

④ 지원자의 관리 소홀 또는 허용되지 않은 공유로 발생한 불이익은 지원자의 귀책 범위에서 지원자가 부담합니다. 다만 회사 또는 채용사의 귀책사유로 발생하거나 확대된 손해는 제외합니다.

## 제11조. 지원자에 대한 통지

① 회사는 지원자가 제공하거나 채용사를 통하여 제공된 이메일 주소, 서비스 화면 내 안내 또는 그 밖에 사전에 안내한 방법으로 지원자에게 필요한 정보를 통지할 수 있습니다.

② 다수 지원자에게 공통되는 일반적인 통지는 서비스 화면 또는 회사 웹사이트에 7일 이상 게시하는 것으로 개별 통지를 갈음할 수 있습니다.

③ 약관의 중대한 변경, 면접 취소·마감 변경, 이용제한, 보안사고, 개인정보 권리 처리 결과 등 지원자의 권리·의무 또는 진행 중인 면접에 중대한 영향을 미치는 사항은 회사가 지원자의 연락처를 보유한 경우 이메일 또는 서비스 화면으로 개별 통지합니다.

④ 지원자는 이메일 주소 등 직접 제공한 연락처를 정확하게 입력하여야 합니다. 지원자가 잘못 제공한 연락처로 통지를 받지 못한 경우 회사는 그에 대한 책임을 부담하지 않습니다. 다만 회사 또는 채용사의 귀책사유로 연락처가 잘못 등록되거나 통지가 도달하지 않은 경우에는 그러하지 않습니다.

## 제12조. 서비스의 제공 및 일시 중지

① 회사는 AI 면접, 질문 생성·제시, 응답 수집, 영상·음성·텍스트 처리, 분석 리포트 생성·제공 및 이에 부수하는 기능을 제공합니다. 실제 제공 범위는 채용사가 설정한 프로젝트와 면접 전 안내에 따라 달라질 수 있습니다.

② 회사는 안정적인 서비스 제공을 위하여 합리적으로 노력합니다. 다만 점검, 장애, 보안조치 또는 운영상·기술상 상당한 사유가 있는 경우 서비스의 전부 또는 일부를 일시 중지할 수 있습니다.

③ 정기점검 등 예측 가능한 사유로 서비스를 중지하는 경우 회사는 중지 일시, 사유 및 예상 기간을 미리 공지합니다. 긴급한 보안조치, 장애 복구 등 사전 통지가 어려운 경우에는 필요한 조치를 먼저 한 후 지체 없이 알립니다.

④ 면접 진행 중 회사가 관리하는 시스템의 장애가 발생한 경우 회사는 장애 기록을 확인하고 지원자와 채용사에 필요한 사실을 안내하며, 면접 재개 또는 재응시가 가능하도록 합리적인 조치를 합니다.

⑤ 응시기한 연장이나 채용절차상 조치는 채용사가 결정하되, 회사는 지원자의 귀책 없는 장애로 불이익이 발생하지 않도록 필요한 사실확인과 전달에 협조합니다.

## 제13조. AI 면접 서비스

① 회사의 AI 시스템은 채용공고, 지원 서류 및 채용사가 설정한 평가요소를 바탕으로 초기 질문과 직무 역량 항목을 생성할 수 있습니다. 채용사는 초기 질문과 평가요소를 검토·수정·추가하여 확정하며, 면접 중에는 지원자의 답변 내용에 따라 AI가 후속 질문을 생성·제시할 수 있습니다.

② AI 면접 진행 중 지원자의 영상·음성·텍스트 응답이 기록·수집될 수 있으며, 면접 종료 후 분석 리포트와 면접데이터가 해당 채용사에 제공될 수 있습니다. 구체적인 처리·제공 범위는 프로젝트 설정, 개인정보 처리방침 및 면접 전 고지·동의 내용에 따릅니다.

③ 분석 리포트는 채용 담당자의 검토를 위한 보조자료입니다. 서비스는 합격·불합격을 자동으로 결정하거나 실행하지 않으며, 채용사는 AI 분석 리포트만을 근거로 지원자를 평가하거나 합격·불합격을 결정해서는 안 됩니다. 최종 채용 결정은 채용사가 지원 서류, 면접 답변, 직무 관련 요소 및 독립적인 평가 기준을 종합하여 사람이 수행합니다.

④ 회사는 면접 영상·음성에서 얼굴, 음성 또는 그 밖의 신체적·생리적·행동적 특징값을 추출하여 특정 개인을 식별하기 위한 생체인식정보를 생성하지 않으며, 지원자의 표정, 시선, 감정, 음성 톤 등 비언어적 요소를 분석하거나 평가하지 않습니다.

⑤ 회사는 서비스가 AI에 기반하여 운영된다는 사실을 AI 면접 전에 안내하고, AI가 생성한 질문과 분석 리포트에는 AI에 의하여 생성되었다는 사실을 표시합니다. 면접 질문의 음성 안내가 합성 음성인 경우에도 지원자가 이를 알 수 있도록 안내합니다.

⑥ 회사는 지원자의 개인정보와 면접데이터를 마케팅·광고, 범용 AI 모델의 학습·개선, 다른 채용사의 평가 또는 채용사 간 비교 목적으로 사용하지 않습니다.

⑦ 회사는 관계 법령에 따라 서비스의 고영향 인공지능 해당 여부를 사전에 검토하고 그 결과를 기록·관리합니다. 고영향 인공지능 또는 생성형 인공지능 관련 의무가 적용되는 경우 회사는 사전 고지, 위험관리, 주요 기준에 관한 설명 방안, 이용자 보호, 사람에 의한 관리·감독, 문서 작성·보관 및 그 밖의 법정 조치를 이행합니다.

⑧ 지원자는 회사가 수행한 AI 분석의 목적·절차·주요 고려사항에 대한 설명과 답변 전사·요약 또는 분석 입력의 사실오류 정정을 회사에 요청할 수 있습니다. 회사는 요청 접수 사실과 처리 결과를 합리적인 기간 내에 안내합니다. 제7조 제3항의 프로젝트에서 정정 요청이 회사에 접수된 경우 회사는 이를 해당 채용사에 전달하고 채용사의 적법한 지시에 따라 처리합니다.

⑨ 채용 판단 또는 후속 전형에 대한 이의와 사람에 의한 재검토 요청은 해당 채용사에 할 수 있습니다. 회사와 채용사는 필요한 범위에서 요청 전달과 사실확인에 협조합니다.

⑩ 회사는 채용사가 성별, 연령, 출신지역, 장애, 가족관계 등 관계 법령상 차별이 금지되거나 직무 수행과 무관한 요소를 평가 기준 또는 질문으로 사용하지 않도록 서비스 정책을 운영합니다. 지원자는 부적절한 질문, 차별 우려 또는 접근성 지원의 필요를 회사와 해당 채용사에 알릴 수 있습니다.

⑪ 지원자는 채용사가 설정한 응시 기한 내에 면접을 완료해야 합니다. 다만 채용사의 구독 기간 종료, 이용 한도 소멸 또는 프로젝트 마감으로 지원자가 초대된 면접에 접속할 수 없는 경우 회사는 확인 가능한 범위에서 그 사유를 안내하고 채용사에 문의 또는 재응시 요청을 전달할 수 있는 방법을 제공합니다. 이러한 사유는 본 약관상 지원자의 귀책에 따른 미응시로 보지 않습니다.

⑫ 지원자는 원활한 면접을 위하여 카메라·마이크 권한, 지원 기기·브라우저 및 네트워크 환경을 사전에 점검해야 합니다. 지원자의 기기 결함 또는 네트워크 불안정으로 발생한 중단은 지원자의 귀책 범위에서 지원자가 부담합니다. 회사의 고의·과실 또는 회사가 관리하는 시스템의 장애로 발생하거나 확대된 손해에 대한 회사의 책임은 제한되지 않습니다.

⑬ AI 분석의 설명·정정 및 채용 판단에 대한 이의제기의 구체적인 접수 방법과 연락처는 면접 화면, 고객센터 또는 개인정보 처리방침에서 안내합니다.

## 제14조. 이용 중단, 이용계약 종료 및 개인정보 동의 철회

① 지원자는 면접 시작 전 또는 진행 중 서비스 화면, 고객센터 또는 회사가 안내한 방법을 통하여 서비스 이용을 중단할 수 있습니다.

② 서비스 이용 중단이 해당 채용절차에 미치는 영향은 채용사가 정합니다. 회사는 이용 중단 전에 확인 가능한 영향을 안내하거나 채용사의 안내를 확인할 수 있는 방법을 제공합니다.

③ 면접을 중단한 지원자의 재접속·재응시 가능 여부와 응시기한은 채용사가 정한 기준에 따릅니다. 회사는 기술적으로 가능한 범위에서 채용사의 결정에 따른 재접속·재응시 조치를 지원합니다.

④ 서비스 이용 중단은 개인정보 동의 철회 또는 개인정보 삭제 요청과 동일하지 않습니다. 개인정보의 동의 철회, 열람, 정정·삭제 및 처리정지 요구는 제7조와 적용되는 개인정보 처리방침에 따릅니다.

⑤ 채용사에 이미 제공된 정보에 관한 권리는 해당 채용사에 행사할 수 있으며, 회사는 필요한 범위에서 요청 전달에 협조합니다.

⑥ 지원자에 대한 이용계약은 지원자가 서비스 이용을 중단하거나 해당 AI 면접과 지원자 대상 서비스 제공이 종료된 때에 종료됩니다. 다만 이용계약의 종료는 종료 전에 적법하게 이루어진 개인정보 처리에 영향을 미치지 않으며, 종료 후 개인정보의 보유·파기와 권리 행사는 제7조부터 제9조까지에 따릅니다.

⑦ 이용계약이 종료된 후에도 개인정보 보호, 콘텐츠와 권리의 귀속, 손해배상, 책임 제한 및 분쟁 해결 등 그 성질상 존속할 필요가 있는 조항은 유효합니다.

## 제15조. 서비스의 변경 및 종료

① 회사는 기술적·운영상 필요 또는 서비스 품질 향상을 위하여 서비스의 전부 또는 일부를 변경할 수 있습니다.

② 지원자의 이용에 실질적인 영향을 미치지 않는 변경은 서비스 화면 또는 회사 웹사이트에서 사전 또는 사후 공지할 수 있습니다.

③ 진행 중인 면접의 핵심 기능을 축소·종료하는 등 지원자에게 불리하거나 중대한 변경은 적용일 30일 전까지 변경 내용, 사유 및 적용일을 게시하고, 회사가 연락처를 보유한 지원자에게 개별 통지합니다.

④ 보안사고 대응, 긴급 장애 복구, 법령 또는 관계 기관의 명령 준수 등 사전 통지가 곤란한 경우 회사는 필요한 조치를 먼저 한 후 지체 없이 그 사유와 내용을 알릴 수 있습니다.

⑤ 회사의 사정으로 진행 중인 AI 면접의 핵심 기능을 계속 제공할 수 없는 경우 회사는 채용사와 협의하여 면접 재개, 재응시 또는 합리적인 대체 방법을 제공하기 위해 노력합니다.

## 제16조. 콘텐츠와 권리의 귀속

① 관계 법령상 보호되는 범위에서 서비스 소프트웨어, 화면 구성, 분석 방법, 분석 리포트 템플릿 및 회사가 제작한 콘텐츠에 대한 저작권과 그 밖의 지식재산권은 회사 또는 정당한 권리자에게 귀속됩니다.

② 지원자가 제공한 지원 서류와 면접 응답에 대한 권리는 지원자 또는 정당한 권리자에게 귀속됩니다.

③ 지원자는 회사가 면접 진행, 저장, 전사, 요약, 분석 리포트 생성 및 해당 채용사 제공을 위하여 필요한 범위와 기간 동안 지원 서류와 면접 응답을 저장·복제·전송·변환할 수 있는 비독점적이고 무상의 이용권을 회사에 부여합니다.

④ 제3항의 이용권은 해당 정보가 적법하게 삭제되면 장래를 향하여 종료됩니다. 다만 관계 법령상 보존, 분쟁 대응, 보안 및 삭제 주기에 따른 제한적인 백업에는 영향을 미치지 않습니다.

⑤ 지원자의 응답과 면접데이터를 채용사에 제공하는 것은 지원자 콘텐츠에 대한 소유권을 채용사에 이전하는 것을 의미하지 않습니다. 채용사는 관계 법령, 개인정보 처리방침 및 지원자에게 제공된 고지·동의에 따른 채용 목적 범위에서 이를 이용합니다.

## 제17조. 이용제한

① 회사는 지원자가 다음 각 호의 어느 하나에 해당하는 경우 위반의 성격·정도, 고의성, 반복 여부 및 피해를 고려하여 필요한 최소 범위와 기간으로 서비스 이용을 제한할 수 있습니다.

1. 시스템 해킹, 악성코드 유포, 비정상적인 접근 또는 그 밖의 방법으로 서비스 운영을 방해하는 경우
2. 타인의 명의를 사용하거나 대리 응시를 하는 경우
3. 개인 면접 링크, 인증정보 또는 면접 세션 정보를 무단으로 공유하는 경우
4. 면접 질문이나 서비스 콘텐츠를 정당한 사유 없이 무단으로 유출·복제하거나 상업적으로 이용하는 경우
5. 그 밖에 본 약관 또는 관계 법령을 중대하게 위반하는 경우

② 답변 내용의 진실성이나 채용 적합성에 관한 판단은 채용사가 담당하며, 회사는 답변 내용의 진실성만을 이유로 지원자의 응시를 제재하지 않습니다.

③ 회사는 원칙적으로 조치 전에 제한 사유, 내용, 기간 및 이의신청 방법을 통지합니다. 다만 긴급한 보안 위험, 개인정보 침해 또는 제3자의 급박한 피해를 방지하기 위하여 필요한 경우에는 즉시 제한한 후 지체 없이 통지할 수 있습니다.

④ 지원자는 회사의 조치에 이의가 있는 경우 고객센터를 통하여 소명자료와 함께 이의를 신청할 수 있습니다. 회사는 이의가 정당하다고 판단되는 경우 지체 없이 제한을 해제하거나 필요한 시정조치를 합니다.

## 제18조. 회사의 의무

① 회사는 관계 법령, 본 약관 및 개인정보 처리방침을 준수하며 안정적인 서비스 제공을 위해 합리적으로 노력합니다.

② 회사는 개인정보와 면접데이터의 안전한 처리를 위하여 필요한 관리적·기술적·물리적 보호조치를 이행합니다.

③ 회사는 개인정보 침해사고 또는 중대한 보안사고를 인지한 경우 관계 법령과 개인정보 처리위탁계약에 따라 필요한 통지·신고 및 피해 완화 조치를 이행합니다.

④ 회사는 지원자가 제기한 정당한 의견, 불만, AI 분석 설명·정정 요청 및 이용제한 이의신청을 합리적인 기간 내에 처리하고 그 결과를 안내합니다. 처리가 지연되는 경우에는 가능한 범위에서 그 사유와 예상 일정을 알립니다.

⑤ 회사는 서비스의 AI 기반 운영, AI 생성 결과 및 합성 음성 사용 여부를 관계 법령과 본 약관에 따라 표시·안내합니다.

⑥ 회사는 제6조부터 제8조까지에서 정한 자신의 개인정보 처리 지위에 따라 지원자에게 필요한 고지·동의 절차와 권리 행사 수단을 제공합니다.

## 제19조. 지원자의 의무

① 지원자는 사실에 부합하는 응시 정보를 제공하고 본인이 직접 면접에 응시해야 합니다.

② 지원자는 대리 응시를 하거나 채용사와 회사가 면접 전에 명확히 금지한 부정한 도구·자료를 사용해서는 안 됩니다. 채용사가 허용한 자료와 장애 또는 접근성 지원을 위한 보조기기의 정당한 사용은 부정행위로 보지 않습니다.

③ 지원자는 개인에게 발급된 면접 질문이나 서비스 콘텐츠를 정당한 사유 없이 무단으로 유출·복제하거나 상업적으로 이용해서는 안 됩니다. 다만 정당한 권리 행사, 증거 보존, 관계 기관 신고 또는 법령상 의무 이행을 위하여 필요한 범위에서 이용하는 경우에는 그러하지 않습니다.

④ 지원자는 타인에 대한 협박, 모욕, 지속적인 괴롭힘 또는 그 밖의 위법한 방법으로 서비스 운영을 방해해서는 안 됩니다. 다만 정당한 민원 제기, 오류 신고, 권리 행사 또는 공익신고를 제한하지 않습니다.

⑤ 지원자는 면접 답변이나 첨부자료에 채용에 불필요한 주민등록번호, 건강정보, 정치적 견해 등 민감정보 또는 고유식별정보와 타인의 개인정보가 포함되지 않도록 유의해야 합니다.

⑥ 지원자는 부적절한 질문, 차별 우려, 기술적 장애 또는 접근성 지원의 필요가 있는 경우 회사와 해당 채용사에 알릴 수 있습니다.

## 제20조. 이용요금 및 환불

① 회사는 지원자에게 AI 면접 응시를 위한 이용요금을 부과하지 않습니다.

② 지원자가 서비스 이용대금을 부담하지 않으므로 지원자에게 적용되는 결제·청약철회 또는 환불 절차는 없습니다. 채용사가 회사에 지급하는 구독료와 크레딧의 결제·청약철회·환불은 채용회사와 회사 사이의 계약에 따릅니다.

③ 향후 회사가 지원자 대상 유료 기능을 제공하는 경우 회사는 결제 전에 이용요금, 이용조건, 이용 개시 시점, 청약철회 및 환불 기준을 별도로 고지하고 관계 법령상 필요한 동의를 받습니다.

## 제21조. 손해배상

① 회사의 귀책사유로 지원자에게 손해가 발생한 경우 회사는 관계 법령에 따라 그 손해를 배상합니다.

② 지원자가 자신의 귀책사유로 본 약관 또는 관계 법령을 위반하여 회사에 손해를 발생시킨 경우 지원자는 자신의 귀책 범위에서 그 손해를 배상합니다.

③ 회사와 지원자는 손해가 발생하거나 확대되지 않도록 합리적으로 노력합니다.

## 제22조. 책임 제한

① 회사는 천재지변, 전쟁, 대규모 정전, 기간통신사업자의 통신망 장애 등 회사의 합리적인 통제를 벗어나고 합리적인 예방·복구 조치로도 피하기 어려운 사유로 의무를 이행하지 못한 경우 그 범위에서 책임을 부담하지 않습니다. 회사는 가능한 경우 해당 사유와 예상 영향을 알리고 피해를 줄이기 위해 합리적으로 노력합니다.

② 회사는 채용사의 최종 채용 여부 및 독립적인 인사결정의 결과를 보장하지 않습니다. 다만 회사가 수행한 AI 분석, 개인정보 처리, 보안조치 또는 그 밖에 회사가 담당하는 서비스 업무에 관한 책임까지 배제하는 것은 아닙니다.

③ 회사가 제9조, 개인정보 처리방침 및 관계 법령에 따라 적법하게 개인정보와 면접데이터를 삭제한 경우 회사는 그 삭제로 인한 손실에 대하여 책임을 부담하지 않습니다. 다만 회사의 귀책사유로 정해진 보유기간 전에 삭제하거나 적법한 권리 행사 요청을 이행하지 않은 경우에는 그러하지 않습니다.

④ 지원자의 기기 결함, 지원하지 않는 브라우저 사용 또는 네트워크 불안정으로 서비스 이용에 장애가 발생한 경우 회사는 지원자의 귀책 범위에서 책임을 부담하지 않습니다. 다만 회사의 고의·과실 또는 회사가 관리하는 시스템의 장애로 손해가 발생하거나 확대된 경우에는 그러하지 않습니다.

⑤ 본 조는 회사의 고의 또는 중대한 과실, 생명·신체에 발생한 손해 및 관계 법령상 제한할 수 없는 책임에는 적용되지 않습니다.

## 제23조. 준거법 및 재판관할

① 회사와 지원자 사이의 분쟁에는 대한민국 법을 적용합니다.

② 회사와 지원자는 서비스 이용과 관련한 분쟁이 발생한 경우 상호 협의하여 해결하기 위해 노력합니다.

③ 협의로 해결되지 않는 분쟁의 관할은 「민사소송법」에서 정한 법원으로 합니다.

