## 제2조. 용어의 정의

① 본 약관에서 사용하는 용어의 뜻은 다음과 같습니다.

1. "서비스"란 회사가 제공하는 AI 면접, 질문 생성, 응답 수집, 분석 리포트 제공 및 채용 프로세스 운영에 필요한 부가 기능 일체를 말합니다.
2. "회원"이란 본 약관에 동의하고 회사와 이용계약을 체결하여 서비스를 이용하는 기업 또는 기관 고객을 말합니다.
3. "프로젝트"란 회원이 특정 채용공고 또는 채용 절차를 위하여 생성한 AI 면접 단위를 말합니다.
4. "관리자"란 프로젝트 생성, 구성원 초대, 권한 부여, 결제 등 회원의 서비스 운영 권한을 가진 담당자를 말합니다.
5. "지원자"란 회원의 채용 전형에 참여하거나 AI 면접에 응시하는 개인을 말합니다.
6. "AI 면접"이란 채용공고, 지원 서류 및 회원이 설정하거나 확정한 평가요소를 바탕으로 회사의 시스템이 질문을 생성·제시하고, 지원자의 영상·음성·텍스트 응답을 수집하여 분석 리포트 등을 생성·제공하는 절차를 말합니다.
7. "면접데이터"란 AI 면접 과정에서 생성·수집·기록되는 영상, 음성, 질문과 답변, 전사·요약 텍스트, 평가·분석 결과, 접속·진행 기록 및 그 밖의 관련 데이터를 말합니다.
8. "회원 콘텐츠"란 회원이 서비스에 등록하거나 입력한 채용공고, 지원 서류, 평가요소, 질문, 안내문 및 그 밖의 자료를 말합니다.
9. "유료서비스"란 회사가 정한 이용대가를 지급하고 이용하는 서비스를 말하며, 일정 기간 서비스 이용 권한을 부여받는 구독 플랜을 포함합니다.
10. "구독 기간"이란 회원이 선택한 유료서비스를 이용할 수 있는 기간을 말합니다.
11. "크레딧"이란 회원이 선택한 플랜에 따라 구독 기간 내 지원자에게 서비스를 제공할 수 있는 최대 횟수 또는 이용 단위를 말합니다.
12. "소멸"이란 크레딧의 유효기간이 만료되어 잔여 크레딧을 더 이상 사용할 수 없고 다음 구독 기간으로 이월되지 않는 것을 말합니다.
13. "개별 계약"이란 회사와 회원이 별도로 체결한 주문서, 견적서, 서비스 이용계약서, 서비스 수준 약정, 개인정보 처리위탁계약 및 그 밖의 서면 또는 전자문서 형태의 합의를 말합니다.

② 본 약관에서 정하지 않은 용어는 관계 법령, 개별 계약 및 일반적인 상관례에 따릅니다.

## 제3조. 약관 및 운영정책의 명시와 개정

① 회사는 본 약관과 회사의 상호, 대표자 성명, 영업소 소재지, 사업자등록번호 및 연락처를 회원이 쉽게 확인할 수 있도록 서비스 초기화면 또는 연결화면에 게시합니다.

② 회사는 관계 법령을 위반하지 않는 범위에서 본 약관을 개정할 수 있습니다.

③ 회사가 본 약관을 개정하는 경우 적용일자, 개정사유 및 주요 변경 내용을 명시하여 현행 약관과 함께 적용일 7일 전부터 서비스 홈페이지 또는 서비스 내 공지사항에 게시합니다. 다만 회원의 권리·의무에 중대한 영향을 미치거나 회원에게 불리한 변경은 적용일 30일 전부터 게시하고 회원이 등록한 이메일 주소 또는 서비스 내 알림으로 개별 통지합니다.

④ 회사가 제3항에 따라 개정 약관을 공지 또는 통지하면서 "적용일 전일까지 거부 의사를 표시하지 않으면 개정 약관에 동의한 것으로 본다"는 뜻과 거부 방법을 별도로 명확하게 고지하였음에도 회원이 적용일 전일까지 거부 의사를 표시하지 않은 경우 회원은 개정 약관에 동의한 것으로 봅니다.

⑤ 제4항은 관계 법령상 명시적 동의 또는 별도 동의가 필요한 변경에는 적용하지 않습니다. 회사는 개인정보의 처리 목적·항목 확대, 민감정보 처리, 국외이전 등 관계 법령상 별도의 동의가 필요한 사항에 대하여 해당 동의를 별도로 받습니다.

⑥ 회원은 개정 약관의 적용일 전일까지 회사에 거부 의사를 표시하고 제25조에 따라 이용계약을 해지할 수 있습니다. 회사가 기존 약관을 계속 적용하기 어려운 합리적인 사유가 있는 경우 회사는 상당한 기간을 정하여 이용계약을 종료할 수 있으며, 이 경우 종료일과 사유를 미리 통지하고 제23조에 따라 미사용 유료서비스 대금을 정산합니다.

⑦ 회사는 서비스 운영에 필요한 세부 사항을 운영정책으로 정할 수 있습니다. 운영정책의 제정·개정이 회원의 권리·의무에 중대한 영향을 미치거나 본 약관의 개정과 동일한 효과가 있는 경우 제3항부터 제6항까지의 절차를 따릅니다.

⑧ 개인정보 처리방침의 변경은 해당 방침에서 정한 절차에 따릅니다. 다만 정보주체의 권리에 중요한 영향을 미치는 변경은 관계 법령에 따라 이메일, 서비스 내 알림 등 별도의 방법으로 안내합니다.

⑨ 법령 변경을 그대로 반영하는 경우, 오탈자 수정 또는 회원에게 유리하거나 권리·의무에 실질적인 영향을 미치지 않는 변경은 적용 후 지체 없이 공지할 수 있습니다.

## 제4조. 약관의 해석과 적용 순서

① 회사와 회원은 서비스 이용에 관하여 개별 계약을 체결할 수 있습니다.

② 본 약관과 개별 계약의 내용이 충돌하는 경우 개별 계약이 우선합니다. 다만 개인정보 처리 역할, 재위탁, 안전성 확보조치, 정보주체 권리 대응 및 개인정보 반환·파기에 관해서는 개인정보 처리위탁계약을 우선 적용합니다.

③ 회사의 개인정보 처리방침은 개인정보 처리에 관한 구체적인 사항을 정합니다. 본 약관과 개인정보 처리방침의 내용이 충돌하는 경우 관계 법령 및 해당 개인정보 처리관계의 성격에 부합하도록 해석합니다.

④ 본 약관에서 정하지 않은 사항은 「약관의 규제에 관한 법률」, 「전자상거래 등에서의 소비자보호에 관한 법률」, 「전기통신사업법」, 「정보통신망 이용촉진 및 정보보호 등에 관한 법률」, 「개인정보 보호법」, 「인공지능 발전과 신뢰 기반 조성 등에 관한 기본법」 등 관계 법령과 일반적인 상관례에 따릅니다.

⑤ 본 약관의 일부 조항이 관계 법령에 따라 무효가 되더라도 나머지 조항의 효력에는 영향을 미치지 않습니다.

## 제5조. 이용계약의 성립

① 이용계약은 서비스를 이용하려는 기업 또는 기관이 본 약관에 동의하고 회사가 정한 절차에 따라 회원가입 또는 주문·구매를 신청한 후 회사가 가입 완료, 주문 승인 또는 서비스 활성화를 통지함으로써 성립합니다.

② 회원을 대표하여 이용계약을 체결하거나 관리자로 등록하는 사람은 회원을 적법하게 대표하거나 회원으로부터 필요한 권한을 부여받았음을 보증합니다.

③ 회사는 다음 각 호의 어느 하나에 해당하는 경우 가입 또는 이용 신청을 거절하거나 승낙을 유보할 수 있습니다.

1. 신청 내용에 허위, 누락 또는 오류가 있는 경우
2. 신청자가 회원을 대표하거나 대리할 권한이 없음이 확인된 경우
3. 과거 본 약관 또는 관계 법령을 중대하게 위반하여 이용이 제한된 사실이 있는 경우
4. 서비스 설비의 여유가 없거나 기술상·보안상 장애가 있는 경우
5. 위법하거나 부당한 목적으로 서비스를 이용하려는 것이 합리적으로 의심되는 경우
6. 그 밖에 신청을 승낙하기 어려운 합리적인 사유가 있는 경우

④ 회사가 신청을 거절하거나 승낙을 유보하는 경우 원칙적으로 그 사유를 신청자에게 알립니다. 다만 법령 위반, 보안 위험 또는 제3자의 권리 침해 우려로 구체적인 사유를 알리기 어려운 경우에는 그 범위를 제한할 수 있습니다.

⑤ 회원은 회사에 제공한 회원·관리자 정보와 결제정보를 정확하고 최신 상태로 유지하여야 합니다.

## 제6조. 증빙자료의 제출

① 회사는 서비스 제공, 계약·정산, 보안 및 권한 관리를 위하여 필요한 범위에서 회원에게 사업자등록증, 재직증명서, 권한 위임 확인서 등 증빙자료의 제출을 요청할 수 있습니다.

② 회사는 제출받은 자료를 요청 목적 범위에서만 이용하며, 목적이 달성되거나 보유 필요가 없어진 경우 관계 법령에 따라 지체 없이 파기합니다.

③ 회사가 증빙자료에 포함된 개인정보를 처리하는 경우 그 처리 목적, 항목 및 보유기간을 개인정보 처리방침 또는 별도의 고지를 통해 안내합니다.

## 제7조. 계정 및 접근권한

① 회원은 계정정보를 정확하고 최신 상태로 유지하고, 계정과 비밀번호를 선량한 관리자의 주의로 관리하여야 합니다.

② 회원은 계정이나 접근권한을 제3자에게 공유·양도·대여하거나 담보로 제공할 수 없습니다. 다만 회사가 제공하는 구성원 초대와 권한 관리 기능을 이용하는 경우에는 그러하지 않습니다.

③ 회원은 관리자와 면접데이터 접근 권한을 업무상 필요한 최소 인원에게만 부여하고 정기적으로 검토하여야 합니다.

④ 회원은 계정 도용, 무단 접근 또는 보안사고를 인지한 경우 즉시 회사에 알리고 회사의 합리적인 보안조치에 협조하여야 합니다.

⑤ 회원의 관리 소홀 또는 허용되지 않은 계정 공유로 발생한 손해는 회원의 귀책 범위에서 회원이 부담합니다. 다만 회사의 귀책사유로 발생하거나 확대된 손해는 제외합니다.

## 제8조. 회원에 대한 통지

① 회사는 회원이 제공한 이메일 주소, 서비스 내 알림 또는 그 밖에 당사자가 합의한 방법으로 회원에게 통지할 수 있습니다.

② 다수 회원에게 공통되는 일반적인 통지는 서비스 홈페이지 또는 서비스 내 공지사항에 7일 이상 게시하는 것으로 개별 통지를 갈음할 수 있습니다.

③ 약관, 요금, 자동갱신, 핵심 기능의 축소·종료 또는 데이터 처리 등 회원의 권리·의무에 중대한 영향을 미치는 사항은 관련 조항에서 정한 기간 동안 게시하고 회원이 등록한 이메일 주소와 서비스 내 알림으로 개별 통지합니다.

④ 회원은 통지를 받을 수 있도록 담당자와 이메일 주소를 최신 상태로 유지하여야 합니다. 회원이 연락처 변경사항을 회사에 알리지 않아 통지를 받지 못한 경우 회사는 회원이 마지막으로 제공한 연락처로 통지한 것에 대하여 책임을 부담하지 않습니다. 다만 회사의 고의 또는 과실로 통지가 도달하지 않은 경우에는 그러하지 않습니다.

## 제9조. 개인정보의 보호 및 처리

① 회사와 회원은 서비스 이용 과정에서 처리되는 개인정보에 관하여 「개인정보 보호법」 등 관계 법령, 회사의 개인정보 처리방침, 지원자에게 제공된 고지·동의 내용 및 당사자 사이에 체결된 개인정보 처리위탁계약을 준수합니다.

② 회원은 지원자 초대와 채용 절차 운영을 위하여 회사에 제공하거나 회사로 하여금 처리하게 하는 개인정보에 대하여 적법한 처리 근거를 확보하고, 지원자에게 필요한 고지와 동의 절차가 이행되도록 협조하여야 합니다.

③ 일반적인 서비스 이용관계에서 회사가 지원자의 동의를 직접 받아 개인정보를 처리하는 경우 회사는 해당 개인정보의 개인정보처리자로서 개인정보 처리방침과 동의 내용에 따라 개인정보를 처리하고, 지원자의 별도 동의 또는 법령상 근거에 따라 해당 회원에게 제공합니다.

④ 제3항의 제공은 회원의 채용전형 진행, 평가·검토 및 결과 확인 목적 범위에서 이루어지며 구체적인 제공 항목, 시점과 방법은 서비스 설정, 개인정보 처리방침 및 지원자에게 제공된 고지·동의에 따릅니다.

⑤ 회원은 회사로부터 제공받거나 서비스에서 열람한 지원자 개인정보와 면접데이터를 해당 채용 목적 범위에서만 이용하고, 필요한 최소 인원에게만 접근 권한을 부여하며, 목적 달성 또는 보유기간 종료 시 관계 법령에 따라 안전하게 파기합니다.

⑥ 회사는 지원자 개인정보와 AI 면접 결과를 마케팅·광고, 범용 AI 모델의 학습·개선, 다른 회원의 평가 또는 회원 간 비교 목적으로 사용하지 않으며, 해당 지원자가 지원하거나 응시하는 회원 외의 다른 회원에게 제공하거나 열람하게 하지 않습니다.

⑦ 지원자가 개인정보의 열람, 정정·삭제, 처리정지 또는 동의 철회 등 권리를 행사하는 경우 회사와 회원은 각자의 개인정보 처리 지위에 따라 지체 없이 필요한 조치를 이행하고 상호 협조합니다.

## 제10조. 개인정보 처리위탁계약을 체결한 경우의 특칙

① 회사가 특정 회원 또는 프로젝트에 관하여 회원과 별도의 개인정보 처리위탁계약을 체결한 경우 해당 계약의 범위에서 회원은 개인정보처리자이자 위탁자가 되고 회사는 회원의 적법한 지시에 따라 지원자 개인정보를 처리하는 수탁자가 됩니다.

② 제1항의 경우 개인정보 처리위탁계약, 회원의 개인정보 처리방침 및 지원자에게 제공된 고지·동의 내용이 본 약관과 함께 적용됩니다. 개인정보 처리 역할과 관련하여 본 약관과 개인정보 처리위탁계약이 충돌하는 경우 개인정보 처리위탁계약이 우선합니다.

③ 제1항의 경우 회사가 회원의 지시에 따라 지원자 개인정보와 AI 면접 결과를 회원에게 전달하는 것은 위탁업무의 수행에 해당합니다.

④ 회원은 개인정보처리자로서 지원자에 대한 고지·동의, 국외이전의 법적 근거 확보 등 관계 법령상 의무를 이행할 책임을 부담하며, 회사는 위탁받은 목적과 범위를 벗어나 지원자 개인정보를 이용하거나 제3자에게 제공하지 않습니다.

⑤ 회사는 재위탁이 필요한 경우 개인정보 처리위탁계약에서 정한 절차에 따라 회원의 사전 동의를 받습니다.

⑥ 위탁업무가 종료되거나 처리 목적이 달성된 경우 회사는 개인정보 처리위탁계약과 회원의 적법한 지시에 따라 개인정보를 반환하거나 파기합니다.

⑦ 제1항의 프로젝트에 관한 지원자의 권리 행사 요청이 회사에 접수된 경우 회사는 이를 해당 회원에게 전달하며, 회원은 관계 법령에서 정한 기간 내에 필요한 조치를 이행합니다.

## 제11조. 개인정보 처리의 위탁, 재위탁 및 국외이전

① 회사는 서비스 제공을 위해 필요한 경우 외부 업체에 개인정보 처리업무를 위탁할 수 있으며, 수탁업체와 위탁업무의 구체적인 내용은 개인정보 처리방침에 공개합니다.

② 회사는 수탁업체와 필요한 계약을 체결하고 개인정보가 안전하게 처리되도록 관리·감독합니다.

③ 제10조가 적용되는 프로젝트의 재위탁, 안전성 확보조치, 회원의 감독, 개인정보 침해사고 통지, 정보주체 권리 대응 및 계약 종료 후 개인정보의 반환·파기에 관해서는 개인정보 처리위탁계약에 따릅니다.

④ 회사가 개인정보 처리업무를 국외에 위탁하는 등 개인정보의 국외이전이 발생하는 경우 이전되는 항목·국가·시기·방법·이전받는 자 및 보유기간 등을 개인정보 처리방침에서 공개하고 관계 법령에 따라 필요한 고지·동의 절차를 이행합니다.

⑤ 위탁업무의 내용, 수탁업체 또는 국외이전의 내용이 변경되는 경우 회사는 관계 법령에 따라 지체 없이 개인정보 처리방침을 통하여 공개하고 필요한 고지·동의 절차를 이행합니다.

⑥ 회사는 개인정보의 분실·도난·유출·위조·변조 또는 훼손 등 침해사고를 인지한 경우 관계 법령과 개인정보 처리위탁계약에서 정한 절차와 기한에 따라 회원 및 관계 기관에 통지하고, 피해를 줄이기 위한 합리적인 조치를 취합니다.

## 제12조. 면접데이터의 보관 및 파기

① 개인정보 처리위탁계약이 적용되는 프로젝트의 개인정보와 면접데이터의 보유·반환·파기 기간은 해당 계약과 회원의 적법한 지시에 따릅니다.

② 그 밖의 일반적인 서비스 이용관계에서 회사는 지원자의 개인정보와 면접데이터를 AI 면접 응시 완료일부터 1년간 보관하며, 면접에 응시하지 않은 지원자의 정보는 초대일부터 1년간 보관합니다. 회원 또는 지원자에게 이보다 짧은 기간이 고지된 경우에는 그 기간을 우선 적용합니다.

③ 제1항 또는 제2항의 보유기간이 지나기 전이라도 해당 채용공고·프로젝트 또는 면접 정보가 삭제되거나 회사가 적법한 삭제 요청을 받은 경우 회사는 관계 법령상 보존 의무가 있는 정보를 제외하고 해당 정보를 지체 없이 파기합니다.

④ 회원은 관계 법령상 또는 채용 업무상 보존이 필요한 자료를 적용되는 보유기간 내에 열람·확보하여야 합니다.

⑤ 회사가 본 조, 개인정보 처리방침 및 개인정보 처리위탁계약에 따라 적법하게 데이터를 파기한 경우 회원은 파기된 데이터의 복구를 요청할 수 없습니다. 다만 회사의 귀책사유로 보유기간 전에 데이터가 삭제되거나 적법한 반환·내보내기 요청이 이행되지 않은 경우에는 그러하지 않습니다.

## 제13조. 서비스의 제공 및 일시 중지

① 회사는 회원에게 AI 면접, 질문 생성, 응답 수집, 분석 리포트 생성·제공 및 이에 부수하는 기능을 제공합니다. 세부 기능과 제공 범위는 회원이 이용하는 플랜 또는 개별 계약에 따라 달라질 수 있습니다.

② 회사는 연중무휴 1일 24시간 서비스를 제공하기 위해 노력합니다. 다만 점검, 장애, 보안조치 또는 운영상·기술상 상당한 사유가 있는 경우 서비스의 전부 또는 일부를 일시 중지할 수 있습니다.

③ 정기점검 등 예측 가능한 사유로 서비스를 중지하는 경우 회사는 중지 일시, 사유 및 예상 기간을 미리 공지합니다.

④ 장애, 보안사고, 긴급한 시스템 조치 또는 불가항력 등 사전 통지가 어려운 경우 회사는 필요한 조치를 먼저 한 후 지체 없이 회원에게 알립니다.

⑤ 회사는 서비스 중지로 인한 영향을 줄이고 정상적인 서비스를 복구하기 위해 합리적으로 노력합니다.

## 제14조. AI 면접 서비스

① 회사의 AI 시스템은 채용공고, 지원 서류 및 회원이 설정한 평가요소를 바탕으로 질문과 직무 역량 항목을 생성할 수 있습니다. 회원은 생성된 질문과 평가요소를 검토·수정·추가하여 최종 확정할 수 있으며, AI 시스템은 지원자의 답변을 바탕으로 후속 질문을 생성할 수 있습니다.

② AI 면접 진행 중 지원자의 영상·음성·텍스트 응답이 기록될 수 있으며, 면접 종료 후 분석 리포트와 면접데이터가 회원에게 제공될 수 있습니다. 구체적인 처리·제공 범위는 서비스 설정, 개인정보 처리방침, 지원자에게 제공된 고지·동의 및 개인정보 처리위탁계약에 따릅니다.

③ 서비스는 지원자의 합격·불합격을 자동으로 결정하거나 실행하지 않습니다. 분석 리포트는 채용 담당자의 검토를 위한 참고자료이며, 회원은 AI 분석 리포트만을 근거로 합격·불합격을 결정해서는 안 됩니다.

④ 회사는 면접 영상·음성에서 얼굴, 음성 또는 그 밖의 신체적·생리적·행동적 특징값을 추출하여 특정 개인을 식별하기 위한 생체인식정보를 생성하지 않으며, 지원자의 표정, 시선, 감정, 음성 톤 등 비언어적 요소를 분석하거나 평가하지 않습니다.

⑤ 회사는 서비스가 AI에 기반하여 운영된다는 사실을 지원자에게 AI 면접 전에 안내하고, AI가 생성한 질문과 분석 리포트에는 AI에 의해 생성되었다는 사실을 표시합니다. 면접 질문의 음성 안내가 합성 음성인 경우에도 지원자가 이를 알 수 있도록 안내합니다.

⑥ 회사는 서비스의 고영향 인공지능 해당 여부를 관계 법령에 따라 검토하고, 고영향 인공지능 또는 생성형 인공지능 관련 의무가 적용되는 경우 사전 고지, 위험관리, 설명 방안, 이용자 보호, 사람에 의한 관리·감독, 문서 작성·보관 및 그 밖의 법정 조치를 이행합니다.

⑦ 회원은 회사가 제6항의 의무를 이행하는 데 합리적으로 필요한 정보 제공과 운영 절차에 협조합니다.

⑧ 지원자가 AI 분석의 처리 과정 또는 회사가 생성한 결과에 관하여 문의하거나 이의를 제기하는 경우 회사가 대응하고, 채용 판단 또는 후속 전형에 관한 문의·이의는 회원이 대응합니다. 회사와 회원은 필요한 범위에서 관련 요청을 서로 전달하고 처리에 협조합니다.

⑨ 회원은 지원자에게 AI 면접의 진행 방식, AI 사용 사실, 개인정보와 면접데이터의 처리·제공 사실을 적법하게 안내하고 필요한 고지·동의 절차가 이행되도록 협조하여야 합니다.

## 제15조. 서비스의 변경 및 종료

① 회사는 기술적·운영상 필요 또는 서비스 품질 향상을 위하여 서비스의 전부 또는 일부를 변경할 수 있습니다.

② 회원의 이용에 실질적인 영향을 미치지 않는 변경은 서비스 내에서 사전 또는 사후 공지할 수 있습니다.

③ 유료서비스의 핵심 기능을 축소하거나 폐지하는 등 회원에게 불리하거나 중대한 변경은 적용일 30일 전까지 변경 내용, 사유 및 적용일을 서비스에 게시하고 이메일로 개별 통지합니다.

④ 보안사고 대응, 긴급 장애 복구, 법령 또는 행정기관의 명령 준수 등 사전 통지가 곤란한 경우 회사는 필요한 조치를 먼저 한 후 지체 없이 그 사유와 내용을 통지할 수 있습니다.

⑤ 회사의 사정으로 유료서비스의 핵심 기능을 영구적으로 종료하여 회원이 계약 목적을 달성할 수 없는 경우 회사는 합리적인 대체 서비스를 제공하거나 제23조에 따라 이용하지 못한 부분의 이용대금을 환불합니다.

## 제16조. 정보의 제공 및 광고

① 회사는 서비스 운영, 고객지원, 보안, 업데이트 및 계약 이행에 필요한 정보를 공지, 이메일 또는 서비스 내 메시지로 제공할 수 있습니다.

② 회사가 영리 목적의 광고성 정보를 전송하는 경우 관계 법령에 따라 필요한 동의를 받고 수신거부 방법을 제공합니다.

③ 회사는 서비스 화면에 제3자의 광고 또는 외부 서비스 정보를 표시할 수 있습니다.

④ 회원과 광고주 또는 외부 서비스 제공자 사이의 거래는 해당 당사자 사이의 책임으로 이루어집니다. 다만 회사의 고의 또는 과실로 발생한 손해에 대한 책임은 제외되지 않습니다.

## 제17조. 콘텐츠와 지식재산권

① 관계 법령상 보호되는 범위에서 서비스, 소프트웨어, 화면 구성, 분석 방법, 분석 리포트 템플릿 및 회사가 제작한 콘텐츠에 대한 저작권과 그 밖의 지식재산권은 회사 또는 정당한 권리자에게 귀속됩니다.

② 회원 콘텐츠에 대한 권리는 회원 또는 정당한 권리자에게 귀속됩니다.

③ 회원은 회사가 이용계약을 이행하고 서비스를 운영하는 데 필요한 범위에서 회원 콘텐츠를 저장·복제·표시·전송·변환할 수 있는 비독점적이고 무상의 이용권을 회사에 부여합니다.

④ 회원이 회원 콘텐츠를 삭제하거나 이용계약이 종료되면 제3항의 이용권은 장래를 향하여 종료됩니다. 다만 감사, 백업, 법령 준수, 분쟁 대응 또는 사업 연속성을 위한 제한적 보관·캐시와 삭제 전에 적법하게 이루어진 이용에는 영향을 미치지 않습니다.

⑤ 회원은 회원 콘텐츠가 제3자의 권리를 침해하지 않고 관계 법령을 위반하지 않음을 보증합니다.

⑥ 회사는 회원이 유효한 이용계약 기간 동안 서비스에서 적법하게 생성·제공받은 질문, 분석 리포트 및 화면 출력물을 해당 회원의 내부 채용 검토 목적으로 저장·복제·공유할 수 있는 비독점적이고 양도 불가능한 이용권을 부여합니다. 이용계약이 종료된 후에도 회원이 계약 기간 중 적법하게 제공받아 보관 중인 산출물을 관계 법령상 보존 의무의 이행 또는 채용 관련 분쟁 대응 목적으로 보관·열람하는 것은 허용되며, 이 경우에도 제7항 및 제8항의 제한은 계속 적용됩니다.

⑦ 회원은 회사의 사전 동의 없이 회사가 제공한 질문, 분석 리포트, 템플릿 또는 서비스 산출물을 재판매하거나 경쟁 서비스 개발, 범용 AI 모델 학습 또는 지원자·회원 간 비교 데이터베이스 구축 목적으로 사용할 수 없습니다.

⑧ 회원은 면접데이터와 지원자 정보를 해당 채용 목적 외로 이용하거나 제3자에게 무단으로 제공할 수 없습니다.

## 제18조. 이용제한

① 회사는 회원이 다음 각 호의 어느 하나에 해당하는 경우 위반의 성격과 정도에 따라 경고, 시정요구, 서비스 일부 제한, 일시정지 또는 이용계약 해지 조치를 할 수 있습니다.

1. 시스템 해킹, 악성코드 유포, 비정상적인 접근 또는 과도한 호출 등으로 서비스 운영을 방해하는 경우
2. 계정이나 접근권한을 무단으로 공유·양도·판매하는 경우
3. 지원자 개인정보나 면접데이터를 채용 목적 외로 이용하거나 무단 제공하는 경우
4. 불법·차별적 평가 또는 완전히 자동화된 채용 결정을 위하여 서비스를 사용하는 경우
5. 제3자의 권리 또는 관계 법령을 침해하는 콘텐츠를 등록하는 경우
6. 이용요금을 지급하지 않는 경우
7. 그 밖에 본 약관 또는 관계 법령을 중대하게 위반하는 경우

② 회사는 원칙적으로 조치 전에 위반 사유, 조치 내용 및 시정기간을 통지합니다. 다만 긴급한 보안 위험, 개인정보 침해, 중대한 법령 위반 또는 제3자의 급박한 피해를 방지하기 위해 필요한 경우에는 즉시 조치한 후 지체 없이 통지할 수 있습니다.

③ 회원은 회사의 조치에 이의가 있는 경우 통지를 받은 날부터 7일 이내에 고객센터를 통해 소명자료와 함께 이의를 신청할 수 있습니다.

④ 회사는 이의신청이 정당하다고 판단되는 경우 지체 없이 제한을 해제하거나 필요한 시정조치를 합니다.

⑤ 지원자 답변 내용의 진실성이나 채용 적합성에 관한 판단은 회원이 담당하며, 회사는 답변 내용의 진실성만을 이유로 지원자의 응시를 제재하지 않습니다.

## 제19조. 이용요금 및 요금 변경

① 유료서비스의 종류, 이용요금, 과금 기준, 구독 기간, 결제 주기, 자동갱신 여부 및 크레딧은 서비스 화면, 주문서, 견적서 또는 개별 계약에서 정합니다.

② 회사가 이용요금을 인상하거나 과금 기준을 회원에게 불리하게 변경하는 경우 적용일 30일 전까지 변경 내용과 적용일을 공지하고 이메일로 개별 통지합니다.

③ 변경된 요금과 과금 기준은 원칙적으로 변경 적용일 이후 처음 개시되는 구독 기간부터 적용하며 이미 결제된 구독 기간에는 소급 적용하지 않습니다.

④ 회원이 요금 변경에 동의하지 않는 경우 다음 갱신일 전까지 구독을 해지할 수 있습니다.

⑤ 이용요금에 부가가치세가 별도로 부과되는 경우 회사는 결제 화면, 견적서, 주문서 또는 개별 계약에서 이를 표시합니다.

## 제20조. 구독 플랜 및 크레딧

① 회원은 선택한 플랜에 따라 구독 기간 동안 사용할 수 있는 크레딧을 부여받습니다. 유상으로 구매한 크레딧의 유효기간은 해당 구독 기간으로 하며, 별도 표시가 없는 월 구독 플랜의 기본 구독 기간은 결제일부터 30일입니다.

② 구독 기간 내 사용하지 않은 잔여 크레딧은 기간 만료 시 자동 소멸하며 다음 구독 기간으로 이월되거나 현금으로 환불되지 않습니다. 다만 개별 계약, 구매 화면 또는 제23조에서 달리 정한 경우에는 그에 따릅니다.

③ 크레딧은 다음 각 호의 시점에 차감됩니다.

1. 직접 초대: 회원이 특정 지원자에게 면접 초대 메일을 발송한 때
2. 공유 링크 응시: 지원자가 공유 링크를 통해 접속하여 필수 약관·동의 절차를 완료한 때
3. API 연동 생성: 회원이 API를 통해 지원자를 생성한 때
4. 그 밖에 구매 화면 또는 개별 계약에서 차감 시점을 명확히 정한 유료 기능을 사용한 때

④ 제3항에 따라 크레딧이 차감되었으나 지원자가 실제 면접을 시작하지 않은 상태에서 프로젝트가 종료된 경우 회사는 해당 크레딧을 동일한 구독 기간의 잔여 한도로 복구합니다. "실제 면접 시작" 여부는 카메라·마이크 테스트 진입, 첫 질문의 제시 또는 그 밖에 서비스 화면에서 안내한 객관적인 기준으로 판단합니다.

⑤ 제4항에 따른 복구 시점에 구독 기간이 이미 만료된 경우 크레딧은 복구되지 않습니다. 다만 회사의 귀책사유로 복구가 지연된 경우에는 합리적인 사용기간을 부여합니다.

⑥ 무료체험 또는 프로모션으로 지급된 무상 크레딧은 회사가 별도로 정한 유효기간과 사용조건을 따르며 유상 크레딧보다 먼저 차감될 수 있습니다. 회사는 무상 크레딧 지급 시 유효기간, 차감 순서 및 사용조건을 안내합니다.

## 제21조. 유료서비스 결제 및 정기결제

① 회원은 신용카드, 계좌이체, 세금계산서 발행 후 입금 또는 회사가 제공하는 그 밖의 방법으로 이용요금을 결제할 수 있습니다.

② 회사는 결제 전에 이용요금 총액, 구독 기간, 자동갱신 여부, 다음 결제일, 크레딧의 유효기간과 소멸, 유료서비스 이용 개시 시점 및 환불 제한을 회원이 확인할 수 있도록 표시합니다.

③ 자동갱신 상품은 회원이 다음 결제일 전에 갱신 중단을 신청하지 않는 한 동일한 기간 단위로 갱신됩니다.

④ 회사는 자동갱신 상품의 다음 결제일과 결제 예정 금액을 원칙적으로 결제일 7일 전까지 이메일 또는 서비스 내 알림으로 안내합니다.

⑤ 무료체험에서 유료서비스로 전환되거나 정기결제 금액·주기가 변경되는 경우 회사는 전환 또는 변경 전에 결제일, 금액 및 주기를 회원에게 안내하고 관계 법령상 필요한 동의를 받습니다.

⑥ 회원은 다음 결제 예정일 전까지 서비스 내 기능 또는 고객센터를 통해 정기결제의 갱신을 중단할 수 있습니다.

⑦ 결제 실패, 연체 또는 미납이 발생한 경우 회사는 회원에게 상당한 기간을 정하여 납부를 요청할 수 있으며, 그 기간 내에 결제가 완료되지 않으면 서비스의 전부 또는 일부를 제한할 수 있습니다. 반복적인 결제 실패 또는 명백한 지급 거절이 있는 경우 회사는 자동갱신을 중단할 수 있습니다.

⑧ 회사는 이용계약 체결, 약관 동의, 결제 및 환불에 관한 기록을 관계 법령에서 정한 기간 동안 보관합니다.

## 제22조. 청약철회

① 본 서비스는 기업의 채용 업무를 위한 B2B 서비스입니다. 관계 법령상 회원에게 청약철회권이 적용되는 경우에는 해당 법령이 정한 바에 따릅니다. 관계 법령상 청약철회권의 적용 여부와 별개로, 회사는 회원이 결제일로부터 7일 이내에 청약철회를 요청하고 유료서비스의 이용이 개시되지 않은 경우 결제금액 전액을 환불합니다.

② 다음 각 호 중 하나가 발생한 경우 유료서비스의 이용이 개시된 것으로 봅니다.

1. 회원이 지원자에게 직접 초대 메일을 발송하여 크레딧이 차감된 경우
2. 공유 링크를 통해 지원자가 접속하고 필수 약관·동의 절차를 완료하여 크레딧이 차감된 경우
3. 회원이 API를 통해 지원자를 생성하여 크레딧이 차감된 경우
4. 그 밖에 구매 화면 또는 주문서에서 이용 개시 시점으로 명확히 고지하고 회원이 확인한 유료 기능을 실제 사용한 경우

③ 제2항에도 불구하고 해당 이용 건에 대하여 차감된 크레딧이 제20조 제4항에 따라 전부 복구된 경우에는 그 이용 건만으로 유료서비스의 이용이 개시된 것으로 보지 않습니다.

④ 회사는 청약철회 제한 사유, 유료서비스의 이용 개시 시점과 환불 제한을 결제 화면 등 회원이 결제 전에 쉽게 확인할 수 있는 곳에 명확하게 표시하고 회원이 이를 확인할 수 있도록 합니다.

⑤ 청약철회는 서비스 내 기능, 회사가 안내한 이메일 또는 고객센터를 통해 신청할 수 있습니다. 회사는 접수 후 지체 없이 접수 사실과 처리 결과를 회원에게 안내합니다.

## 제23조. 구독 해지 및 환불

① 제22조에 따른 청약철회가 인정되는 경우 회사는 청약철회 의사표시를 받은 날(계좌이체·세금계산서 등 수납 확인이 필요한 결제수단의 경우 수납 확인일)부터 3영업일 이내에 원 결제수단으로 결제대금 전액을 환급합니다. 원 결제수단으로 환급할 수 없는 경우 회원과 협의한 방법으로 환급합니다.

② 법정 청약철회, 제22조에 따른 미사용 전액 환불, 회사 귀책 환불 및 과오납 환급에는 결제대행 수수료나 송금 수수료를 공제하지 않습니다.

③ 법령상 또는 본 약관상 의무가 아닌 회원 편의상 예외적 환불에 실제로 발생한 반환 불가능한 비용을 공제하려는 경우 회사는 그 기준을 결제 전에 명확히 고지하고 관계 법령이 허용하는 범위에서만 공제할 수 있습니다.

④ 유료서비스의 이용이 개시된 후 회원의 사정으로 구독을 중도 해지하는 경우 이미 결제된 현재 구독 회차의 이용료는 환불하지 않습니다. 회원은 해당 구독 기간의 말일까지 서비스를 이용할 수 있고, 다음 결제 주기부터 갱신이 중단됩니다. 다만 개별 계약, 구매 화면 또는 관계 법령에서 달리 정한 경우에는 그에 따릅니다.

⑤ 회사의 귀책사유로 유료서비스의 핵심 기능을 계속 이용할 수 없거나 회사가 서비스를 영구 종료하는 경우 회사는 복구, 이용기간 연장 또는 대체 서비스 제공 중 합리적인 조치를 취합니다. 그러한 조치로도 회원이 계약 목적을 달성할 수 없는 경우 다음 각 호의 기준에 따라 환불합니다.

1. 기간 기준 정액제: 현재 구독 회차 결제금액에 전체 구독일수 대비 이용하지 못한 잔여일수의 비율을 곱한 금액
2. 크레딧 단독 구매형: 해당 구매금액에 전체 유상 크레딧 대비 미사용 유상 크레딧의 비율을 곱한 금액
3. 기간과 크레딧을 함께 기준으로 하는 상품: 구매 화면 또는 개별 계약에서 정한 기준. 별도 기준이 없는 경우 제1호와 제2호에 따라 산정한 금액 중 회원에게 유리한 금액

⑥ 제3조 제6항 또는 제31조 제3항에 따라 회사가 미사용 유료서비스 대금을 정산하여야 하는 경우 제5항 각 호의 환불 산정 기준을 준용합니다.

⑦ 무료체험, 프로모션 또는 그 밖에 회원이 대가를 지급하지 않고 받은 크레딧이나 이용권은 현금으로 환불하지 않습니다.

⑧ 별도의 개별 계약에서 환불 조건을 달리 정한 경우 해당 계약이 우선합니다. 다만 관계 법령상 배제할 수 없는 회원의 권리를 제한하지 않습니다.

⑨ 회원에게 미납된 이용요금 또는 반환하여야 할 금액이 있는 경우 회사는 관계 법령이 허용하는 범위에서 환불금과 상계할 수 있습니다.

## 제24조. 이용요금 과오납의 조정

① 이용요금이 과오납된 경우 회사는 과오납 전액을 원 결제수단으로 환급합니다. 동일한 방법으로 환급할 수 없는 경우 회사는 회원에게 알리고 협의한 방법으로 환급합니다.

② 회사의 귀책사유로 과오납이 발생한 경우 회사는 수수료를 공제하지 않습니다. 회원의 귀책사유로 과오납이 발생한 경우에는 관계 법령이 허용하는 범위에서 환급에 실제로 필요한 비용만 공제할 수 있습니다.

③ 회사는 환급에 필요한 정보를 받은 날(수납 확인이 필요한 결제수단의 경우 수납 확인일)부터 3영업일 이내에 환급 절차를 진행합니다. 회원이 동의하는 경우 다음 결제대금에서 과오납액을 차감할 수 있습니다.

④ 이용요금 환급을 받을 회원에게 미납금이 있는 경우 회사는 관계 법령이 허용하는 범위에서 환급금과 미납금을 상계할 수 있습니다.

## 제25조. 회원의 계약 해지 및 종료 후 데이터 처리

① 회원은 서비스 화면, 관리자 요청, 고객센터 또는 당사자가 합의한 서면 방식으로 이용계약의 해지를 신청할 수 있습니다.

② 정기 구독의 해지는 다음 결제 예약을 취소하는 방식으로 처리되며, 회원은 이미 결제한 구독 기간의 말일까지 서비스를 이용할 수 있습니다. 다만 제22조에 따른 청약철회, 회사의 귀책사유에 따른 해지·환불 또는 개별 계약에 별도 규정이 있는 경우에는 그에 따릅니다.

③ 이용계약이 종료되면 회원의 서비스와 면접데이터에 대한 접근 권한은 종료됩니다. 회원은 종료 전에 관계 법령상 또는 채용 업무상 보존이 필요한 자료를 열람·확보하여야 합니다.

④ 회사의 사정으로 이용계약이 종료되거나 서비스를 영구 종료하는 경우 회사는 관계 법령, 지원자에게 고지된 보유기간 및 개인정보 처리위탁계약에 위반되지 않는 범위에서 회원에게 종료 전에 합리적인 데이터 내보내기 기간과 방법을 안내합니다.

⑤ 회사는 관계 법령, 개인정보 처리방침 및 개인정보 처리위탁계약에 따라 개인정보와 면접데이터를 반환하거나 파기합니다.

⑥ 해지 시점까지 발생한 이용요금의 정산과 환불은 제23조에 따르며 미지급 대금이 있는 경우 회원은 해지와 관계없이 이를 지급하여야 합니다.

⑦ 해지 후에도 미지급 대금, 비밀유지, 지식재산권, 개인정보 보호, 손해배상, 책임 제한 및 분쟁해결 등 성질상 존속하여야 하는 조항은 유효합니다.

## 제26조. 비밀유지

① 회사와 회원은 이용계약의 체결 또는 서비스 이용 과정에서 상대방으로부터 제공받은 기술상·영업상 비공개 정보(이하 "비밀정보")를 이용계약의 이행 목적으로만 사용하고, 해당 목적에 필요한 임직원 및 법률·회계 등 전문자문인 외의 제3자에게 공개하지 않습니다. 비밀정보를 제공받는 사람에게도 본 조와 동등한 수준의 비밀유지 의무가 부과되어야 합니다.

② 다음 각 호의 정보는 비밀정보에 포함되지 않습니다.

1. 제공받을 당시 이미 적법하게 보유하고 있던 정보
2. 수령 당사자의 책임 없는 사유로 공개된 정보
3. 비밀정보를 사용하지 않고 독자적으로 개발한 정보
4. 비밀유지 의무 없이 제3자로부터 적법하게 취득한 정보
5. 상대방이 서면으로 공개를 승인한 정보

③ 법령, 법원 또는 관계 기관의 적법한 명령에 따라 비밀정보를 공개하여야 하는 경우 수령 당사자는 법령상 허용되는 범위에서 사전에 상대방에게 알리고 공개 범위를 최소화합니다.

④ 각 당사자는 이용계약이 종료되거나 상대방이 합리적으로 요청하는 경우 관계 법령상 보관하여야 하는 정보를 제외하고 비밀정보를 반환하거나 파기합니다.

⑤ 본 조의 의무는 이용계약 종료 후 3년간 존속합니다. 다만 개인정보와 영업비밀은 관계 법령 또는 그 성질상 보호가 필요한 기간 동안 보호합니다.

## 제27조. 회사의 의무

① 회사는 본 약관과 관계 법령을 준수하며 지속적이고 안정적인 서비스 제공을 위해 합리적으로 노력합니다.

② 회사는 개인정보와 면접데이터의 안전한 처리를 위하여 필요한 관리적·기술적·물리적 보호조치를 이행합니다.

③ 회사는 개인정보 침해사고 또는 중대한 보안사고를 인지한 경우 관계 법령과 개인정보 처리위탁계약에 따라 필요한 통지와 신고를 하고 피해를 줄이기 위한 조치를 취합니다.

④ 회사는 회원이 제기한 정당한 의견이나 불만을 합리적인 기간 내에 처리하고, 처리가 지연되는 경우 그 사유와 예상 일정을 안내합니다.

⑤ 회사는 이용계약의 체결, 변경, 해지, 결제 및 환불 절차를 회원이 쉽게 이용할 수 있도록 제공합니다.

⑥ 회사는 서비스의 AI 기반 운영, AI 생성 결과 및 합성 음성 사용 여부를 관계 법령과 본 약관에 따라 표시·안내합니다.

⑦ 회사는 제9조 및 제10조에서 정한 자신의 개인정보 처리 지위에 따라 지원자에게 필요한 고지·동의 절차를 이행합니다.

## 제28조. 회원의 의무

① 회원은 제9조 및 제10조에서 정한 자신의 개인정보 처리 지위에 따라 지원자에게 필요한 고지·동의 절차를 이행하여야 합니다.

② 회원은 회사에 제공하거나 회사로 하여금 처리하게 하는 지원자 개인정보에 대하여 적법한 처리 근거를 확보하고 내부 접근통제를 이행하여야 합니다.

③ 회원이 지원자의 별도 동의를 받기 전에 회사를 통하여 최초 초대 메일을 발송하도록 하는 경우 회원은 지원자 정보의 제공과 그에 수반되는 국외이전에 필요한 법적 근거를 미리 확보하여야 합니다. 해당 근거가 확보되지 않은 경우 회원은 직접 초대 안내를 발송하거나 국외이전이 발생하지 않는 방법을 사용하여야 합니다.

④ 회원은 지원자에게 채용에 불필요한 주민등록번호, 건강정보 등 민감정보 또는 고유식별정보의 제출을 요구해서는 안 됩니다.

⑤ 회원은 면접데이터의 열람·다운로드 권한을 업무상 필요한 최소 인원에게만 부여하고 해당 채용 목적 범위에서만 이용하여야 합니다.

⑥ 회원은 AI 분석 리포트만을 근거로 지원자의 합격·불합격을 자동 결정해서는 안 되며, 지원 서류, 면접 답변, 직무 관련 요소 및 독립적인 평가 기준을 종합하여 사람이 최종 채용 결정을 하도록 하여야 합니다.

⑦ 회원은 성별, 연령, 출신지역, 장애, 가족관계 등 관계 법령상 차별이 금지되거나 직무 수행과 무관한 요소를 평가 기준이나 질문으로 설정해서는 안 됩니다.

⑧ 회원은 본 약관, 운영정책 및 관계 법령을 준수하고 회사의 보안조치, 이용제한 및 사고 대응 요청에 합리적으로 협조하여야 합니다.

⑨ 회원은 이용요금을 정해진 기한에 지급하여야 합니다.

⑩ 회원이 본 약관 또는 관계 법령을 위반하여 회사나 제3자에게 손해를 발생시킨 경우 회원은 자신의 귀책 범위에서 그 손해를 배상합니다.

## 제29조. 손해배상 및 제3자 청구

① 회사 또는 회원이 자신의 귀책사유로 본 약관 또는 관계 법령을 위반하여 상대방에게 손해를 발생시킨 경우 귀책 당사자는 상대방에게 발생한 직접적이고 통상적인 손해를 배상합니다.

② 회원 콘텐츠, 회원이 확정한 질문·평가요소 또는 회원의 위법한 개인정보 처리로 제3자가 회사에 청구를 제기한 경우 회원은 자신의 귀책 범위에서 회사를 방어하고 그 손해를 배상합니다.

③ 제2항의 경우 회사는 제3자 청구 사실과 내용을 지체 없이 회원에게 알리고, 회원이 방어와 합의를 주도할 수 있도록 합리적으로 협조합니다.

④ 회원은 회사에 비금전적 의무를 부담시키거나 회사의 책임을 인정하는 합의를 하려면 회사의 사전 동의를 받아야 하며, 회사는 합리적인 이유 없이 동의를 거절하지 않습니다.

⑤ 회사의 귀책사유로 발생하거나 확대된 손해는 회원의 책임에서 제외합니다.

⑥ 회사의 지식재산권 침해, 개인정보 보호 또는 보안 의무 위반에 관한 별도 배상 조건은 주문서, 서비스 수준 약정 또는 개인정보 처리위탁계약에서 정할 수 있습니다.

## 제30조. 책임 제한

① 회사는 천재지변, 전쟁, 정부의 조치, 기간통신사업자의 장애 등 회사의 합리적인 통제를 벗어난 사유로 의무를 이행하지 못한 경우 그 범위에서 책임을 부담하지 않습니다. 회사는 가능한 경우 회원에게 해당 사유와 예상 영향을 통지하고 피해를 줄이기 위해 합리적으로 노력합니다.

② 회사는 회원의 채용 결과나 인사결정을 보장하지 않습니다. AI 질문과 분석 리포트는 채용 담당자의 검토를 위한 참고자료이며, 회원은 적법하고 독립적인 기준에 따라 사람이 최종 판단하도록 하여야 합니다.

③ 어느 당사자도 특별손해, 간접손해 또는 결과손해에 대하여 그러한 손해의 가능성을 알았거나 알 수 있었더라도 책임을 부담하지 않습니다. 다만 당사자의 고의 또는 중대한 과실로 인한 손해에는 적용하지 않습니다.

④ 본 약관과 관련한 각 당사자의 총 손해배상책임은 손해 발생 원인이 된 사건 직전 12개월 동안 회원이 회사에 실제 지급한 이용료 총액을 한도로 합니다.

⑤ 제3항과 제4항은 다음 각 호의 책임에는 적용하지 않습니다.

1. 당사자의 고의 또는 중대한 과실로 인한 손해
2. 생명 또는 신체에 발생한 손해
3. 회원의 미지급 이용요금
4. 회원이 지원자 개인정보 또는 면접데이터를 목적 외로 이용·제공하거나 유출하여 발생한 책임
5. 제26조(비밀유지) 위반으로 인한 책임
6. 제29조 제2항에 따른 제3자 청구에 대한 배상·방어 책임
7. 관계 법령상 제한할 수 없는 책임

⑥ 개인정보 보호·보안 의무 위반에 대한 책임한도는 개인정보 처리위탁계약에서 별도로 정할 수 있습니다. 별도 약정이 없는 경우 본 조의 일반 책임한도를 적용하되, 제5항 각 호에 해당하는 책임에는 적용하지 않습니다.

⑦ 회사가 제12조, 개인정보 처리방침 및 개인정보 처리위탁계약에 따라 적법하게 면접데이터를 삭제한 경우 회사는 그 삭제로 인한 손실에 대하여 책임을 부담하지 않습니다. 다만 회사의 귀책사유로 정해진 보유기간 전에 삭제하거나 적법한 반환·내보내기 요청을 이행하지 않은 경우에는 그러하지 않습니다.

## 제31조. 계약상 지위의 양도

① 회원은 회사의 사전 서면 동의 없이 이용계약상 지위 또는 권리·의무의 전부나 일부를 제3자에게 양도하거나 담보로 제공할 수 없습니다.

② 회사는 합병, 분할, 영업양도 또는 서비스 사업의 이전으로 이용계약상 지위가 승계되는 경우 회원에게 미리 통지합니다.

③ 제2항의 승계로 회원의 권리·의무에 중대한 불이익이 발생하는 경우 회원은 통지를 받은 날부터 승계일 전까지 이용계약을 해지할 수 있으며, 회사는 제23조에 따라 미사용 유료서비스 대금을 정산합니다.

## 제32조. 준거법 및 재판관할

① 본 약관과 이용계약은 대한민국 법령에 따라 해석되고 적용됩니다.

② 회사와 회원은 서비스 이용과 관련한 분쟁이 발생한 경우 상호 협의하여 해결하기 위해 노력합니다.

③ 협의로 해결되지 않는 분쟁의 관할은 「민사소송법」에서 정한 법원으로 합니다.

