### 개정 사유

도입 문의 및 서비스소개서 신청 절차를 개선하면서 수집하는 정보가 변경되었습니다. 연락처를 필수 항목으로 변경하고, 문의 경로 확인을 위한 항목을 새로 추가했습니다. 실제 수집 내용과 처리방침을 일치시키기 위해 관련 조항을 개정합니다.

### 주요 변경 내용

제2조(개인정보의 처리 목적·항목·수집방법 및 보유기간) 중 **고객문의 및 고충처리** 항목이 다음과 같이 변경되었습니다.

| 구분 | 변경 전 | 변경 후 |
| --- | --- | --- |
| 처리 목적 | 문의자 확인, 문의·민원 내용 확인, 사실조사 및 처리 결과 통보 | 기존 목적에 **서비스 소개 자료 제공 및 도입 상담 안내** 추가 |
| 처리 항목 | 성명, 이메일 주소, 회사명, 문의 내용 및 답변 이력 | 기존 항목에 **연락처, 직무·직책, 유입 경로** 추가 |
| 수집방법 | 문의자가 직접 입력, 상담 과정에서 생성 | 기존 방법에 **서비스 이용 과정에서 자동 수집** 추가 |
| 보유기간 | 문의 또는 고충처리 완료일부터 1년 | 문의, 고충처리 또는 **자료 제공** 완료일부터 1년 |

