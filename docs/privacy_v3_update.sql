## 제1조. 적용 범위 및 회사의 역할

1. 본 개인정보 처리방침은 회사가 운영하는 AI 면접 서비스 '슈퍼코더(Supercoder)'와 회사 웹사이트를 이용하는 채용사, 기업회원, 지원자 및 웹사이트 방문자에게 적용됩니다.

2. 회사는 기업회원의 가입 및 계정 관리, 서비스 이용계약 이행, 결제·정산, 고객문의 대응, 웹사이트 운영 및 보안 등 회사가 처리 목적과 방법을 결정하는 개인정보에 대하여 **개인정보처리자**의 지위에서 처리합니다.

3. 회사가 채용사의 요청에 따라 지원자 초대, AI 면접 진행, 영상·음성의 녹화·전송, 음성의 텍스트 변환, 질문 생성, 답변 분석 및 AI 분석 리포트 생성을 수행하는 경우, 회사는 채용사가 정한 목적과 범위에서 지원자 개인정보를 처리하는 **수탁자**입니다.

4. 제3항의 경우 지원자를 초대한 채용사는 지원자 개인정보의 처리 목적, 항목, 보유기간 및 법적 근거를 결정하는 **위탁자이자 개인정보처리자**입니다. 회사는 채용사의 지시와 개인정보 처리 위탁계약에 따라 지원자 개인정보를 처리합니다.

5. 회사는 채용사를 대신하여 지원자 동의 화면과 동의 기록 기능을 제공할 수 있습니다. 이 경우에도 개인정보 및 민감정보 동의의 주체는 해당 채용사이며, 본 방침이나 회사의 서비스 이용약관은 채용사 명의의 개별 동의서와 채용사의 개인정보 처리방침을 대체하지 않습니다.

6. 채용사별 프로젝트에 따라 처리 항목, 보유기간 및 동의 내용이 달라질 수 있습니다. 지원자는 응시하는 채용사가 제시한 동의서와 개인정보 처리방침에서 해당 채용 절차에 적용되는 구체적인 내용을 확인할 수 있습니다.

7. 회사가 보안사고 조사, 부정이용 방지 또는 법적 의무 이행을 위하여 필요한 최소한의 정보를 독립적으로 처리하는 경우에는 본 방침에 공개된 목적과 기간 내에서만 처리합니다.

