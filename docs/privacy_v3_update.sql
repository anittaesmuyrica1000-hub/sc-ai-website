## 제8조. 개인정보의 파기

1. 회사는 보유기간이 경과하거나 처리 목적이 달성되는 등 개인정보가 불필요하게 된 경우 지체 없이 해당 개인정보를 파기합니다.

2. 지원자 개인정보는 제2조에서 정한 시점 중 가장 먼저 도래하는 때를 기준으로 파기합니다. 관계 법령에 따라 계속 보존해야 하는 정보가 있는 경우에는 해당 정보만 별도의 데이터베이스 또는 논리적으로 분리된 영역에 보관하고 법령에서 정한 목적 외에는 이용하지 않습니다.

3. 개인정보의 파기 절차와 방법은 다음과 같습니다.

   - **파기 절차:** 파기 사유가 발생한 개인정보를 확인하고 회사의 내부 승인 절차에 따라 파기합니다.
   - **전자적 파일:** 복구 또는 재생되지 않도록 안전한 삭제, 덮어쓰기 또는 암호화 키 폐기 등 기술적으로 적절한 방법으로 파기합니다.
   - **종이 문서:** 분쇄기로 분쇄하거나 소각하는 방법으로 파기합니다.
   - **회사 관리 백업 데이터:** 운영 데이터 파기 후 7일 이내에 백업 보존주기에 따라 순차적으로 삭제하며, 삭제 전에는 복구 목적 외의 처리를 제한합니다.

4. 재수탁자가 관리하는 데이터는 제4조와 제5조에 공개된 주기에 따라 삭제합니다.

   - ElevenLabs의 TTS 생성 이력은 삭제 API 호출 시 운영 데이터베이스에서 즉시 삭제되고, 백업은 최대 30일 이내 만료됩니다. 디버깅·모더레이션 로그는 재수탁자의 보안·이상 이용 방지 및 문제 해결 정책에 따라 제한적으로 보관될 수 있습니다.
   - Agora의 실시간 영상·음성 스트림은 저장되지 않으며, 통신 메타데이터는 제4조와 제5조에 기재된 기간 후 삭제됩니다.
   - Azure AI Speech의 배치 전사 작업과 결과는 삭제 API 호출 또는 설정된 `timeToLiveHours`에 따라 처리 완료 후 최대 31일 이내 삭제됩니다.
   - Google Workspace 메일은 제2조, 제4조 및 제5조의 보유기간이 종료되면 삭제합니다.

