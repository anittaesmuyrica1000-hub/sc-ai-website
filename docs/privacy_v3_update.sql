## 제12조. 개인정보 처리방침의 변경

1. 본 개인정보 처리방침을 변경하는 경우에는 변경 내용과 시행일을 정보주체가 쉽게 확인할 수 있도록 회사 웹사이트 등을 통하여 시행 전에 공개합니다.

2. 정보주체의 권리에 중요한 영향을 미치는 변경이 있는 경우에는 관계 법령에 따라 전자우편, 서비스 내 알림 등 별도의 방법으로 안내합니다.

3. 개인정보 처리방침의 시행 및 개정 이력은 다음과 같습니다.

| 구분 | 시행일자 | 주요 변경 내용 |
|---|---|---|
| 최초 시행 | 2026년 2월 1일 | 최초 제정 |
| 개정 | 2026년 6월 29일 | 개인정보 처리 목적·보유기간·위탁 현황 개정 |
| 개정 | **2026년 8월 1일** | 위탁자·수탁자 역할 명확화, 목적·항목·수집방법·보유기간 통합, 재위탁·국외이전 및 AI 처리 고지 정비, 전체 조문 재구성 |

본 방침은 **2026년 8월 1일**부터 적용됩니다.

이전의 개인정보 처리방침은 아래에서 확인하실 수 있습니다.

