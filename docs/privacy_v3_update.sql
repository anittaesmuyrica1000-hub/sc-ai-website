2. 회사 일반 웹사이트에서는 이용 현황과 이용자 상호작용에 관한 통계를 분석하기 위하여 Google Analytics 분석 쿠키를 사용할 수 있습니다. 분석 쿠키는 이용자가 별도로 동의한 경우에만 사용하며, 동의 전에는 관련 스크립트가 실행되거나 정보가 전송되지 않도록 합니다.

