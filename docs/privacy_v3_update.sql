## 제3조. 개인정보의 제3자 제공

1. 회사는 회사가 개인정보처리자로서 처리하는 개인정보를 정보주체의 동의가 있거나 관계 법령에 특별한 근거가 있는 경우를 제외하고 제3자에게 제공하지 않습니다.

2. 회사가 수탁자로서 처리하는 지원자 개인정보와 AI 면접 결과를 해당 지원자를 초대한 채용사에 전달하는 것은 채용사로부터 위탁받은 AI 면접 업무의 수행에 해당하며, 회사가 독립적인 목적으로 제3자에게 제공하는 것이 아닙니다.

3. 회사는 지원자 개인정보를 해당 지원자를 초대한 채용사 외의 다른 채용사에 제공하거나 열람하게 하지 않습니다.

4. 수사기관 등의 적법한 요청이 있거나 관계 법령에 따라 개인정보 제공이 필요한 경우에는 해당 법령이 정한 범위에서 제공할 수 있습니다.

