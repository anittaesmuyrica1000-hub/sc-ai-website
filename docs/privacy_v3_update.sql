국외이전의 내용은 본 방침 및 전자우편·서비스 내 알림 등 전자적 방법으로 안내합니다. 이전받는 자, 이전 국가, 이전 항목, 목적 또는 보유·이용기간이 변경되는 경우에는 관계 법령에 따라 본 방침을 개정하고 필요한 고지·동의 절차를 이행합니다.

