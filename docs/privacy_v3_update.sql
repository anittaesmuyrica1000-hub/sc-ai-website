## 제6조. AI 면접·민감정보 및 채용 의사결정

1. 회사의 AI 면접 서비스는 채용공고·지원 서류 기반 질문 생성, 질문의 합성 음성 생성, 면접 답변 음성의 텍스트 변환, 답변 요약, 기술 경험·직무 역량 분석 및 채용 담당자 검토용 AI 분석 리포트 생성에 AI 기술을 사용합니다.

2. 회사의 서비스는 지원자의 합격·불합격을 **자동으로 결정하거나 실행하지 않습니다.** AI 분석 리포트는 채용사의 채용 담당자가 지원 서류와 면접 답변을 직접 종합 검토할 때 사용하는 참고자료이며, 최종 채용 결정은 채용사 담당자가 수행합니다.

3. 채용사가 회사의 서비스 외의 수단으로 지원자의 권리 또는 의무에 중대한 영향을 미치는 완전히 자동화된 결정을 하는 경우, 해당 채용사가 관계 법령에 따른 거부·설명 요구 및 인적 개입 절차를 운영합니다. 회사는 채용사의 요청에 따라 분석 기준과 처리 과정에 관한 자료 제공을 지원합니다.

4. 회사는 면접 영상·음성에서 얼굴, 음성 또는 그 밖의 신체적·생리적·행동적 특징값을 추출하여 특정 개인을 식별하기 위한 생체인식정보를 생성하지 않습니다. 또한 지원자의 표정, 시선, 감정, 음성 톤 등 비언어적 요소를 분석하거나 평가하지 않습니다.

5. 채용 프로젝트에서 법령상 민감정보가 실제로 처리되거나 채용사가 민감정보에 관한 별도 동의를 요구하는 경우, 채용사는 일반 개인정보 동의와 구분하여 **채용사 명의의 별도 동의**를 받습니다. 회사는 일반 동의와 명확히 구분된 제목·고지내용 및 별도의 미선택 체크박스를 제공하고, 동의 문안·버전·동의 여부·동의 시각 등을 채용사를 대신하여 기록합니다.

6. 회사는 AI 면접 서비스가 AI에 기반하여 운영된다는 사실을 면접 전에 고지합니다. AI가 생성한 질문과 AI 분석 리포트에는 AI에 의하여 생성되었다는 사실을 표시하고, 면접 질문의 음성 안내가 합성 음성이라는 사실도 이용자가 알 수 있도록 안내합니다.

7. 회사는 채용을 위한 판단·평가에 AI가 활용되는 서비스의 특성을 고려하여 고영향 인공지능 해당 여부를 검토합니다. 관련 의무가 적용되는 경우 위험관리, 설명 방안, 이용자 보호, 사람에 의한 관리·감독 및 근거 문서의 5년 보관 등 관계 법령에 따른 조치를 이행하고, 주요 내용을 회사 웹사이트 또는 별도 AI 안내를 통하여 공개합니다.

8. 회사는 지원자 개인정보와 AI 면접 결과를 마케팅·광고, 범용 AI 모델의 학습·개선, 다른 고객사의 평가 또는 고객 간 비교를 위한 자료로 사용하지 않습니다.

9. 지원자는 AI 분석 결과에 관한 문의 또는 이의제기를 해당 채용사에 제기할 수 있습니다. 회사는 채용사의 요청에 따라 관련 내용을 확인하고 필요한 자료를 제공합니다.

10. 지원자는 면접 답변이나 첨부자료에 채용에 불필요한 주민등록번호, 건강정보, 정치적 견해 등 민감정보 또는 고유식별정보가 포함되지 않도록 유의해야 합니다.

