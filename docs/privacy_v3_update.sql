## 제7조. 정보주체와 법정대리인의 권리·의무 및 행사방법

1. 정보주체는 관계 법령에 따라 개인정보의 열람, 정정·삭제, 처리정지 및 동의 철회 등을 요구할 수 있습니다.

2. 기업회원 정보, 회사 웹사이트 이용정보 또는 회사가 독립적인 개인정보처리자로서 처리하는 정보에 관한 권리는 제11조의 개인정보 보호 담당자에게 직접 행사할 수 있습니다.

3. AI 면접 지원자 개인정보에 관한 권리는 원칙적으로 지원자를 초대한 채용사에 행사할 수 있습니다. 지원자가 회사에 직접 요청한 경우 회사는 해당 요청을 채용사에 전달하고, 채용사가 요청을 처리할 수 있도록 필요한 조치를 지원합니다.

4. AI 분석 결과에 대한 설명 또는 이의제기는 채용사에 요청할 수 있습니다. 완전히 자동화된 결정이 이루어진 경우에는 관계 법령이 정한 범위에서 거부, 설명 요구 및 인적 개입에 의한 재처리를 요구할 수 있습니다.

5. 권리 행사는 서면 또는 전자우편 등을 통하여 할 수 있으며, 회사와 채용사는 요청자가 본인 또는 정당한 대리인인지 확인할 수 있습니다.

6. 정보주체가 개인정보의 오류 등에 대한 정정 또는 삭제를 요구한 경우에는 관계 법령에서 달리 정한 경우를 제외하고 정정 또는 삭제가 완료될 때까지 해당 개인정보를 이용하거나 제공하지 않습니다.

7. 법정대리인 또는 위임받은 자가 권리를 행사하는 경우에는 관계 법령에서 정한 위임장을 제출해야 할 수 있습니다. 다른 법령에서 해당 개인정보의 보존을 요구하거나 권리 행사가 제한되는 경우에는 요청의 전부 또는 일부가 제한될 수 있으며, 이 경우 제한 사유를 안내합니다.

