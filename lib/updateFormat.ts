// 모델 출력 마감 처리 — 코드펜스·문서 껍데기·인라인 style을 걷어내고 표를 규격 래퍼로 통일한다.
// (RichEditor에도 같은 취지의 normalizeTables가 있지만, 저장본이 서버에서부터 규격을 맞추도록 여기서 한 번 정리한다.)
export function tidyUpdateHtml(raw: string): string {
  let html = String(raw || "").trim();
  html = html.replace(/^```(?:html)?\s*/i, "").replace(/```\s*$/, "").trim();
  html = html.replace(/<\/?(?:!doctype|html|head|body|meta|style|script)[^>]*>/gi, "");
  html = html.replace(/\sstyle="[^"]*"/gi, "");
  // 표: 기존 래퍼를 걷어낸 뒤 규격 래퍼로 다시 감싼다(모델이 래퍼를 빠뜨려도 동일 결과).
  html = html.replace(/<div\s+class="post-table-wrap"\s*>([\s\S]*?)<\/div>/gi, "$1");
  html = html.replace(/<table[^>]*>/gi, "<table>");
  html = html.replace(
    /<table>([\s\S]*?)<\/table>/gi,
    (_m, inner: string) => `<div class="post-table-wrap"><table class="post-table">${inner}</table></div>`
  );
  html = html.replace(/<hr\s*\/?>/gi, "<hr>");
  html = html.replace(/<p>\s*(?:&nbsp;|<br\s*\/?>)?\s*<\/p>/gi, "");
  return html.replace(/\n{3,}/g, "\n\n").trim();
}
